"""Score PvP builds against a field of opponents and write the matchup matrix (duellab, 2026-11-14).

    python _reference/data/duellab/pvp_field.py --matrix [--n 200] [--write]            # every field build against every other
    python _reference/data/duellab/pvp_field.py --score mage:pvp-frost [mage:...] [--n 200]   # builds against the field

The field is one reference build per class: the community's most-tagged PvP build (pvp-community-builds.json, FIELD), so a build is
judged against what players field. A build's score is its mean win rate over the nine opponents (each class counts the same;
mirror matchups included), with the mean health margin (own share of health left minus the foe's) as the tie-break, a continuous
number that still moves when a matchup sits at 0% or 100%. Duels of a matchup use common random numbers by duel index (duel_run),
so two builds of a class meet the same dice. A model of stated assumptions (duel.py, dtables.py), not a measurement.
"""
import argparse
import concurrent.futures as CF
import json
import os
import pathlib
import statistics
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import duel_run as DR  # noqa: E402

ROOT = HERE.parents[2]
FIELD = [("warrior", "community:tf-arms"), ("rogue", "community:tf-hemo"), ("priest", "community:tf-shadow"),
         ("hunter", "community:tf-mm"), ("warlock", "community:tf-soul-link"), ("paladin", "community:tf-ret-prot"),
         ("shaman", "community:tf-enhancement"), ("druid", "community:tf-feral-resto"), ("mage", "community:tf-frost")]
CLASSES = [c for c, _ in FIELD]


def margin_matchup(a_ref, b_ref, n, seed):
    """(win share, draw share, mean margin) of a against b: margin = a's health share left minus b's, per duel."""
    ca, ra = a_ref
    cb, rb = b_ref
    a = DR.side(ca, DR.load_build(ca, ra)[1])
    b = DR.side(cb, DR.load_build(cb, rb)[1])
    wins = draws = 0
    margins = []
    for i in range(n):
        r, d = DR.duel(a, b, seed * 100_003 + i, swap=bool(i % 2))
        me, foe = (d.b, d.a) if i % 2 else (d.a, d.b)
        wins += r == "A"
        draws += r == "draw"
        margins.append(max(0.0, me.p.hp) / me.p.hp_max - max(0.0, foe.p.hp) / foe.p.hp_max)
    return wins / n, draws / n, statistics.mean(margins)


def _job(args):
    return args, margin_matchup(*args)


def run_jobs(jobs, workers=None):
    workers = workers or max(1, (os.cpu_count() or 2) - 1)
    out = {}
    with CF.ProcessPoolExecutor(max_workers=workers) as ex:
        for args, res in ex.map(_job, jobs):
            out[(args[0], args[1])] = res
    return out


def score(builds, n=200, seed=1, workers=None):
    """{build: {"by": {opponent class: (win, draw, margin)}, "win": mean win, "margin": mean margin}}."""
    jobs = [((c, r), f, n, seed) for c, r in builds for f in FIELD]
    res = run_jobs(jobs, workers)
    out = {}
    for c, r in builds:
        by = {f[0]: res[((c, r), f)] for f in FIELD}
        out[(c, r)] = {"by": by, "win": statistics.mean(v[0] for v in by.values()), "margin": statistics.mean(v[2] for v in by.values())}
    return out


def matrix(n=200, seed=1, workers=None):
    jobs = [(a, b, n, seed) for i, a in enumerate(FIELD) for b in FIELD[i + 1:]]
    res = run_jobs(jobs, workers)
    m = {}
    for (a, b), (w, dr, mg) in res.items():
        m[(a[0], b[0])] = (w, dr, mg)
        m[(b[0], a[0])] = (1.0 - w - dr, dr, -mg)
    for c in CLASSES:
        m[(c, c)] = (0.5, 0.0, 0.0)
    return m


def write_matrix(m, n):
    rows = ["# PvP duel matchups", "",
            "> Generated by `_reference/data/duellab/pvp_field.py --matrix --write`. The duel lab's level-60 one-against-one duels between "
            "each class's reference PvP build (the community's most-tagged on talentsforever.com: `_reference/data/pvp-community-builds.json`), "
            f"{n} duels a matchup, both start orders. A model of stated assumptions (open field, no line of sight, no consumables or racials, "
            "dungeon-blue gear; `_reference/data/duellab/`), not a measurement of the game.", "",
            "Row class's win rate against the column class:", "",
            "| | " + " | ".join(c.title() for c in CLASSES) + " | Mean |", "|---|" + "---|" * (len(CLASSES) + 1)]
    for a in CLASSES:
        ws = [m[(a, b)][0] for b in CLASSES]
        rows.append(f"| **{a.title()}** | " + " | ".join("-" if a == b else f"{w:.0%}" for a, b, w in zip([a] * len(CLASSES), CLASSES, ws))
                    + f" | {statistics.mean(w for b, w in zip(CLASSES, ws) if b != a):.0%} |")
    rows += ["", "Builds: " + "; ".join(f"{c.title()} `{r}`" for c, r in FIELD) + ".", "", "---", "*Generated file — do not edit by hand.*"]
    (ROOT / "_reference" / "pvp-matchups.md").write_text("\n".join(rows) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--matrix", action="store_true")
    ap.add_argument("--score", nargs="*")
    ap.add_argument("--n", type=int, default=200)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--workers", type=int)
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    if a.matrix:
        m = matrix(a.n, a.seed, a.workers)
        print("      " + " ".join(f"{c[:6]:>7}" for c in CLASSES))
        for x in CLASSES:
            print(f"{x[:6]:6}" + " ".join(f"{m[(x, y)][0]:7.0%}" if x != y else "      -" for y in CLASSES))
        if a.write:
            write_matrix(m, a.n)
    if a.score:
        builds = [tuple(x.split(":", 1)) for x in a.score]
        for (c, r), v in sorted(score(builds, a.n, a.seed, a.workers).items(), key=lambda kv: -kv[1]["win"]):
            by = " ".join(f"{k[:4]} {w:.0%}" for k, (w, _, _) in v["by"].items())
            print(f"{c}:{r}: field win {v['win']:.1%}, margin {v['margin']:+.2f} | {by}")


if __name__ == "__main__":
    main()
