"""Write the "Healer lab" section of every healer class README and `_reference/heallab-summary.md` from the healer-lab reports.

    python _reference/data/render_heallab_sections.py [classes]

Reads `<class>/research/raid/heallab/<spec>.json` (written by `_reference/data/heallab/run.py --write`). Generated text; the
section is replaced in place (between its heading and the next `## `). Do not hand-edit the section.
"""
import datetime
import json
import pathlib
import re
import sys
import paths  # noqa: E402
import readme_sections as rs  # noqa: E402
import render_rotations as rrot  # noqa: E402

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
CLASSES = ["priest", "paladin", "shaman", "druid"]
HEAD = "## Healer lab (Monte Carlo raid-healing model)"
SECTION = re.compile(r"## Healer lab \(Monte Carlo raid-healing model\).*?(?=\n## |\Z)", re.S)
SUMMARY = ROOT / "_reference/heallab-summary.md"


def load(cls):
    d = paths.heallab_dir(cls)
    if not d.exists():
        return []
    out = []
    for p in sorted(d.glob("*.json")):
        if p.name.endswith("-calibration.json"):
            continue
        r = json.load(open(p, encoding="utf-8"))
        if "results" in r:
            out.append(r)
    return out


def page_healers(cls):
    """{build id: spec} of the healer builds the raid pages pick (render_modes.py's choice, through render_rotations.page_picks)."""
    return {x["build"]["id"]: x["name"] for x in rrot.page_picks(cls, "raid") if x["build"].get("role") == "healer"}


def render(cls, reports):
    o = [HEAD, "",
         f"[`heallab/`](heallab/) runs the raid-heal builds through the healer lab (`_reference/data/heallab/`): one healer keeps a "
         "tank and four raid members alive for five minutes against boss melee, spikes and raid pulses, with the beta spellbook's heals and the beta tooltips' "
         "talent numbers. **Capacity** is the multiplier on all incoming damage the build survives in 90% of runs; a talent's value is the capacity it adds. "
         "A model of stated assumptions (`heallab/tables.py`: the group, the boss, the healer's gear, consumables), not a measurement. Section generated by "
         f"`_reference/data/render_heallab_sections.py` on {datetime.date.today().isoformat()} — do not hand-edit.", "",
         "✅ = the build the spec's raid page picks.", "",
         "| Spec model | Build | Split | Capacity | Effective HPS | Overheal | Out of mana | Healing split |", "|---|---|---|---|---|---|---|---|"]
    picks = page_healers(cls)
    for r in reports:
        for bid, x in sorted(r["results"].items(), key=lambda kv: -kv[1]["capacity"]):
            s = x["summary"]
            o.append(f"| `{r['spec']}` | `{bid}`" + (f" ✅ {picks[bid]} page" if bid in picks else "") + f" | {x['split']} | {x['capacity']:.3f} | {s['hps']:.0f} | {s['overheal_share'] * 100:.0f}% | {s['oom_time']:.0f} s | "
                     + ", ".join(f"{k} {v * 100:.0f}%" for k, v in list(s["shares"].items())[:5]) + " |")
    for rp in sorted((HERE / "heallab" / "rotations").glob(f"{cls}-*.json")) if (HERE / "heallab" / "rotations").exists() else []:
        rot = json.load(open(rp, encoding="utf-8"))
        if rot.get("changes"):
            o += ["", f"**Tuned heal choice** (`heallab/rotation_opt.py`, {rot.get('date', '?')}, used in every healer-lab run of the class): "
                  + "; ".join(c["change"] for c in rot["changes"]) + f". Capacity of `{rot['build']}` {rot['capacity_before']:.3f} -> "
                  f"{rot['capacity_after']:.3f} ({rot['capacity_after'] / rot['capacity_before'] - 1:+.1%}, on seeds the search never used). "
                  "DOWNRANK: cast the lowest rank that covers the deficit; HOT_REFRESH_DEFICIT: keep the HoT on the tank while it misses more than "
                  "this share of its health; EMERGENCY: below this share a target gets the fastest big heal; RAID_HEAL_AT: raid members below this "
                  "share get healed; GROUP_HEAL_MIN: hurt members for a group heal; POTION_BELOW / POTION_FIRST: mana potion timing."]
    for r in reports:
        for bid, rows in r.get("deltas", {}).items():
            top = sorted([x for x in rows if x["simulated"]], key=lambda x: -x["sim_delta"])[:8]
            o += ["", f"Talents that matter most for `{bid}` (capacity lost when removed): " + ", ".join(f"{x['talent']} {x['sim_delta'] * 100:+.1f}%" for x in top) + "."]
    o.append("")
    return "\n".join(o) + "\n"


def main():
    classes = [c for c in (sys.argv[1:] or CLASSES) if c in CLASSES]
    summary = ["# Healer lab — every healer at a glance", "",
               f"> Generated by `_reference/data/render_heallab_sections.py` on {datetime.date.today().isoformat()} from `<class>/research/raid/heallab/*.json`: "
               "one raid healer keeping a five-member group alive for five minutes in the healer lab (`_reference/data/heallab/`). Capacity = the multiplier on all "
               "incoming damage the build survives in 90% of runs; comparable across classes only under the lab's shared assumptions (same group, boss and gear level). "
               "Simulations of stated assumptions, not measurements. Do not hand-edit.", "",
               "Each row is the build a healer spec's raid page picks (2026-10-15 page audit A6: the table had shown the report's highest capacity, "
               "a candidate no page shows); the class's research raid README lists every build the lab ran.", "",
               "| Class | Spec | Spec model | Page build | Capacity | Effective HPS | Overheal | Healing split | Top talents (capacity lost when removed) |",
               "|---|---|---|---|---|---|---|---|---|"]
    for cls in sorted(CLASSES):   # the summary covers every healer class, the sections only the classes asked for (2026-10-09)
        reports = load(cls)
        if not reports:
            continue
        if cls in classes:
            text = render(cls, reports)
            rs.splice_ordered(paths.scenario_readme(cls, "raid"), "raid", "## Healer lab", text)
            rs.drop(ROOT / cls / "README.md", "## Healer lab")   # moved to raid/README.md (2026-09-27 layout)
        for bid, spec in page_healers(cls).items():
            r = next((r for r in reports if bid in r["results"]), None)
            if r is None:
                summary.append(f"| {cls} | {spec} | - | `{bid}` | not in a healer-lab report | | | | |")
                continue
            x = r["results"][bid]
            sm = x["summary"]
            rows = r.get("deltas", {}).get(bid) or []
            top = sorted([y for y in rows if y["simulated"]], key=lambda y: -y["sim_delta"])[:5]
            summary.append(f"| {cls} | {spec} | `{r['spec']}` | `{bid}` ({x['split']}) | {x['capacity']:.3f} | {sm['hps']:.0f} | {sm['overheal_share'] * 100:.0f}% | "
                           + ", ".join(f"{k} {v * 100:.0f}%" for k, v in list(sm["shares"].items())[:4]) + " | " + (", ".join(f"{y['talent']} {y['sim_delta'] * 100:+.0f}%" for y in top) or "not measured for this build") + " |")
        if cls in classes:
            print(f"{cls}: healer lab section written ({len(reports)} specs)")
    summary.append("")
    SUMMARY.write_text("\n".join(summary) + "\n", encoding="utf-8")
    print(f"wrote {SUMMARY.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
