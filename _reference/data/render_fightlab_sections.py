"""Write the "Fight lab" section of every class's leveling/README.md and the hand draft's "Fight lab" build note from the fight-lab reports.

    python _reference/data/render_fightlab_sections.py [classes...]

Generated text (numbers only, from `<class>/research/leveling/fightlab/<spec>.json`, `sensitivity.md` and
`fightlab/last-rebuild.json`): time per kill by level for the optimizer build and the hand draft, deaths and downtime,
the gear-tier effect, the talents that matter and those that measure zero, the race winner and what is not simulated.
The hand draft's note in `proposed-builds.json` (the one starting "Fight lab (") is rewritten too; run
`validate_builds.py && render_builds.py` afterwards (rebuild.py does).
"""
import collections
import datetime
import json
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
FL = HERE / "fightlab"
sys.path.insert(0, str(HERE / "scorer"))
sys.path.insert(0, str(FL))   # last: `run` is the fight lab runner
from run import MODULES  # noqa: E402
import paths  # noqa: E402
import readme_sections as rs  # noqa: E402
from data_build import BUILD as DATA_BUILD, CAPTURED as DATA_CAPTURED  # noqa: E402

HEAD = "## Fight lab (Monte Carlo fight simulator)"
SECTION = re.compile(r"^## Fight lab \(Monte Carlo fight simulator\)\n.*?(?=^## |\Z)", re.S | re.M)


def pct(x):
    return f"{x * 100:+.0f}%"


def render(cls, P, r, last_cls, cm):
    spec, hand, opt = P["spec"], P["hand"], P["opt"]
    rel = f"fightlab/{spec}.md"
    levels = sorted(r["levels"], key=int)
    top = levels[-1]
    o = [HEAD, "",
         f"[`{rel}`]({rel}) plays {r['fights']} fights per level against same-level normal mobs: beta-client {DATA_BUILD} ability numbers, the client's "
         "base stats and attack table, gear by level from the Classic 1.12 item database (green quest rewards; `_reference/data/fightlab/gear_stats.json`) "
         "and mob health / damage / armor / caster share from the Classic 1.12 creature database (`mob_stats.json`; both unverified for Forever). Every other input is an assumption in `_reference/data/fightlab/tables.py`, "
         f"and [`sensitivity.md`](fightlab/sensitivity.md) shows the ranking with each one moved. Section generated by "
         f"`_reference/data/render_fightlab_sections.py` on {datetime.date.today().isoformat()} — do not hand-edit; the interpretation lives in the build notes.", "",
         "| Build | " + " | ".join(f"L{L}" for L in levels) + f" | Deaths/100 at {top} | Downtime/kill at {top} |", "|---|" + "---|" * (len(levels) + 2)]
    o.append(f"| `{opt}` (optimizer) | " + " | ".join(f"{r['levels'][L]['time_per_kill']:.1f}s" for L in levels) +
             f" | {r['levels'][top]['deaths_per_100']:.1f} | {r['levels'][top]['downtime_per_kill']:.1f}s |")
    for bid, per in r["compare"].items():
        cells = []
        for L in levels:
            rr = per.get(L)
            if rr:
                cells.append(f"{rr['time_per_kill']:.1f}s ({pct((rr['time_per_kill'] - r['levels'][L]['time_per_kill']) / r['levels'][L]['time_per_kill'])})")
            else:
                cells.append("-")
        rt = per.get(top)
        o.append(f"| `{bid}`{' (hand draft)' if bid == hand else ''} | " + " | ".join(cells) + (f" | {rt['deaths_per_100']:.1f} | {rt['downtime_per_kill']:.1f}s |" if rt else " | - | - |"))
    for tier, per in (r.get("gear_tiers") or {}).items():
        cells = []
        for L in levels:
            rr = per.get(L)
            cells.append(f"{rr['time_per_kill']:.1f}s ({pct((rr['time_per_kill'] - r['levels'][L]['time_per_kill']) / r['levels'][L]['time_per_kill'])})" if rr else "-")
        rt = per.get(top)
        o.append(f"| `{opt}` in {tier} (dungeon blues from the item database) | " + " | ".join(cells) + (f" | {rt['deaths_per_100']:.1f} | {rt['downtime_per_kill']:.1f}s |" if rt else " | - | - |"))
    o.append("")
    o.append("Time per kill = fight + loot, travel, eating, drinking, healing and deaths; a build's cell shows its time and the difference to the optimizer build on the same mobs and seeds.")
    o.append("")
    deltas = r.get("deltas") or {}
    if deltas:
        dl = sorted(deltas, key=int)
        hi = dl[-1]
        rows_hi = {x["talent"]: x for x in deltas[hi]["rows"]}
        rows_lo = {x["talent"]: x for x in deltas[dl[0]]["rows"]} if len(dl) > 1 else {}
        best = sorted(rows_hi.values(), key=lambda x: -x["sim_delta"])[:6]
        parts = []
        for x in best:
            lo = rows_lo.get(x["talent"])
            parts.append(f"{x['talent']} {pct(x['sim_delta'])}" + (f" (L{dl[0]} {pct(lo['sim_delta'])})" if lo else ""))
        zero = [x["talent"] for x in rows_hi.values() if abs(x["sim_delta"]) < 0.005]
        neg = [f"{x['talent']} {pct(x['sim_delta'])}" for x in rows_hi.values() if x["sim_delta"] <= -0.01]
        o.append(f"- **Talents that matter** (time per kill lost when the talent is removed from `{opt}` at level {hi}): " + ", ".join(parts) + ".")
        if zero:
            o.append(f"- **Measure about zero** single-target at {hi} (kept for other reasons or not simulated): " + ", ".join(sorted(zero)) + ".")
        if neg:
            o.append(f"- **Measure negative** at {hi} (the sim's rotation loses time with them): " + ", ".join(neg) + ".")
    r60 = r["levels"][top]
    if "caster_share" in r60:
        o.append(f"- **Caster mobs:** {r['levels'][levels[min(1, len(levels) - 1)]]['caster_share'] * 100:.0f}% of pulls at level {levels[min(1, len(levels) - 1)]} are casters "
                 f"(creature-database share); {r60['interrupts_per_kill']:.2f} interrupts per kill at {top}.")
    race = (last_cls or {}).get("race") or {}
    if race.get("mean"):
        means = sorted(race["mean"].items(), key=lambda kv: kv[1])
        names = [(hand if b == "main" else pathlib.Path(b).stem, m) for b, m in means]
        o.append(f"- **Race** (hand draft vs every optimizer candidate, {last_cls.get('started', '')[:10]}, mean time per kill over levels {P['levels'].replace(',', '/')}): "
                 + ", ".join(f"{n} {m:.1f}s" for n, m in names) + f" — fastest: **{names[0][0]}**.")
    rounds = (last_cls or {}).get("rounds")
    if rounds:
        o.append(f"- **Calibration:** the scorer's `{spec}` leveling values were fitted jointly to the hand draft and every candidate in "
                 f"[`fightlab/candidates/`](fightlab/candidates/) ({len(rounds)} round{'s' if len(rounds) != 1 else ''}, "
                 f"{'converged: the optimizer build repeats' if last_cls.get('converged') else 'not converged within the round limit'}).")
    for er in P.get("extra_reports", []):
        ep = paths.fightlab_dir(cls) / f"{er['spec']}.json"
        if not ep.exists():
            continue
        e = json.load(open(ep, encoding="utf-8"))
        parts = []
        for L in ("30", "60"):
            if L in e["levels"]:
                t = e["levels"][L]["time_per_kill"]
                comp = next(iter(e["compare"].values()), {}).get(L)
                parts.append(f"L{L} {t:.1f}s" + (f" ({(t - comp['time_per_kill']) / comp['time_per_kill'] * 100:+.0f}% vs `{next(iter(e['compare']))}`)" if comp else ""))
        o.append(f"- **Other spec, same module:** `{er['spec']}` with `{e['build']}` ([report](fightlab/{er['spec']}.md)): " + ", ".join(parts) +
                 ". Positive = slower than the main spec's optimizer build on the same mobs; the module's priority list was written for the main spec, so this is a rough spec-versus-spec check.")
    for V in P.get("variants", []):
        vname = V.get("report") or (V["spec"] if V["spec"] != P["spec"] else f"{V['spec']}-{V['tag']}")
        vp = paths.fightlab_dir(cls) / f"{vname}.json"
        if not vp.exists():
            continue
        v = json.load(open(vp, encoding="utf-8"))
        parts = []
        for L in ("40", "60"):
            if L in v["levels"]:
                x = v["levels"][L]
                base = r["levels"].get(L)
                parts.append(f"L{L} {x['time_per_kill']:.1f}s per mob in pulls of {x.get('mobs_per_pull', 1):.0f}" + (f" (single-target build {base['time_per_kill']:.1f}s)" if base else "")
                             + f", {x['deaths_per_100']:.1f} deaths/100")
        o.append(f"- **{V.get('label', V['spec'])}:** `{V['spec']}` with `{v['build']}` ([report](fightlab/{vname}.md)): " + "; ".join(parts) + ".")
    ns = r60.get("not_simulated") or []
    o.append(f"- **Not simulated:** {cm.NOT_MODELLED}" + (f" Talents in the build the sim ignores: {', '.join(ns)}." if ns else ""))
    rec = (last_cls or {}).get("race", {}).get("recommended")
    adopted = (last_cls or {}).get("adopted")
    if adopted:
        o.append(f"- **Recommended:** `{hand}` — it now carries `{adopted['winner']}`, adopted on {adopted['date']} ({adopted['gain']:+.1%} vs the previous draft).")
    elif rec and rec != hand:
        o.append(f"- **Recommended:** `{rec}` beats the hand draft by more than the 2% margin but has not been adopted (`rebuild.py {cls} --steps race,adopt,report,regen`).")
    elif rec:
        o.append(f"- **Recommended:** the hand draft `{hand}` (no candidate beats it by more than the 2% margin).")
    o.append("")
    return chr(10).join(o) + chr(10)


def note(cls, P, r, last_cls):
    spec, hand, opt = P["spec"], P["hand"], P["opt"]
    levels = sorted(r["levels"], key=int)
    top = levels[-1]
    per = r["compare"].get(hand, {})
    tpk = "/".join(f"{per[L]['time_per_kill']:.0f}" if L in per else "-" for L in levels)
    diffs = []
    for L in levels:
        if L in per:
            diffs.append((L, (r["levels"][L]["time_per_kill"] - per[L]["time_per_kill"]) / per[L]["time_per_kill"]))
    d60 = next((d for L, d in diffs if L == top), None)
    d30 = next((d for L, d in diffs if L == "30"), None)
    race = (last_cls or {}).get("race") or {}
    winner = race.get("winner")
    deltas = r.get("deltas") or {}
    tops = ""
    if top in deltas:
        rows = sorted(deltas[top]["rows"], key=lambda x: -x["sim_delta"])
        tops = "; top talents at " + top + ": " + ", ".join(f"{x['talent']} {pct(x['sim_delta'])}" for x in rows[:4])
        zero = [x["talent"] for x in rows if abs(x["sim_delta"]) < 0.005]
        if zero:
            tops += "; about zero: " + ", ".join(sorted(zero)[:6])
    return (f"Fight lab (leveling/fightlab/{spec}.md, {datetime.date.today().isoformat()}, generated by render_fightlab_sections.py): time per kill at "
            f"L{'/'.join(levels)} = {tpk} s with Classic 1.12 creature stats and quest greens; the optimizer's {opt} is "
            + (f"{pct(d60)} at {top}" if d60 is not None else "not compared") + (f" and {pct(d30)} at 30" if d30 is not None else "")
            + " (negative = faster)" + (f"; race winner over the leveling: {winner}" if winner else "") + tops + ". See the Fight lab section of leveling/README.md.")


def main():
    classes = sys.argv[1:] or list(MODULES)
    last = json.load(open(FL / "last-rebuild.json", encoding="utf-8")) if (FL / "last-rebuild.json").exists() else {}
    for cls in classes:
        cm = __import__(MODULES[cls][0])
        P = dict(cm.PIPELINE)
        rp = paths.fightlab_dir(cls) / f"{P['spec']}.json"
        if not rp.exists():
            print(f"{cls}: no report {rp.relative_to(ROOT)}")
            continue
        r = json.load(open(rp, encoding="utf-8"))
        last_cls = last.get("classes", {}).get(cls)
        text = render(cls, P, r, last_cls, cm)
        rs.splice_ordered(paths.scenario_readme(cls, "leveling"), "leveling", "## Fight lab", text)
        rs.drop(ROOT / cls / "README.md", "## Fight lab")   # moved to leveling/README.md (2026-09-27 layout)
        bp = ROOT / cls / "research/talents/forever/proposed-builds.json"
        data = json.load(open(bp, encoding="utf-8"), object_pairs_hook=collections.OrderedDict)
        for b in data["builds"]:
            if b["id"] == P["hand"]:
                b["notes"] = [n for n in b.get("notes", []) if not n.startswith("Fight lab (")] + [note(cls, P, r, last_cls)]
        json.dump(data, open(bp, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        subprocess.run([sys.executable, str(HERE / "fmt_json.py"), str(bp)], check=True)
        print(f"{cls}: README section + {P['hand']} note written")


if __name__ == "__main__":
    main()
