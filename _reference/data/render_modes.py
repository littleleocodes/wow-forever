# ------------------------------------------------------------------------------------------------ numbers
def raid_numbers(cls):
    """{build id: {"dps", "raid", "value", "entry", "d", "row"}} over every raid entry: a build's best entry."""
    out = {}
    for x in rs.raid_rows(cls):
        r = x["row"]
        lab = r["label"]
        key = "value" if x["tank"] else "dps"
        cur = out.get(lab)
        if cur is None or (r.get(key) or 0) > (cur["row"].get(key) or 0):
            out[lab] = {"dps": r.get("dps"), "raid": r.get("raid"), "value": r.get("value"), "entry": x["spec"], "d": x["d"], "row": r, "tank": x["tank"]}
    return out


def leveling_numbers(cls):
    """{build id: {level: seconds per kill}} from the fight lab reports (main build and the compared ones) and spec-builds.json."""
    out = {}
    d = paths.fightlab_dir(cls)
    for f in sorted(d.glob("*.json")) if d.exists() else []:
        try:
            rep = json.load(open(f, encoding="utf-8"))
        except ValueError:
            continue
        if not isinstance(rep, dict) or "levels" not in rep or "build" not in rep or rep.get("mob_level_offset") or rep.get("gear", "greens") != "greens":
            continue
        if f.stem.endswith(("-aoe", "sensitivity", "-calibration")):
            continue
        per = {int(L): r["time_per_kill"] for L, r in rep["levels"].items() if isinstance(r, dict) and "time_per_kill" in r}
        out.setdefault(rep["build"], per)
        for bid, lv in (rep.get("compare") or {}).items():
            out.setdefault(bid, {int(L): r["time_per_kill"] for L, r in lv.items() if isinstance(r, dict) and "time_per_kill" in r})
    for bid, info in (GEN.get(cls) or {}).items():
        if info.get("levels"):
            out.setdefault(bid, {int(L): v for L, v in info["levels"].items()})
    return out


def healer_numbers(cls):
    return {r["id"]: r for r in rs.healer_rows(cls)}


def weighted(per):
    tot = sum(int(L) / 10 for L in per)
    return sum(v * int(L) / 10 for L, v in per.items()) / tot if tot else None


# ------------------------------------------------------------------------------------------------ picking builds
def rank_builds(cls, mode, builds, nums):
    """Builds of one spec and mode, best first: raid by training-dummy DPS (tanks: tank value; healers: healing capacity), leveling by
    level-weighted time per kill, PvP hand drafts before generated ones."""
    R, L, H = nums

    def key(b):
        bid = b["id"]
        gen = 1 if b.get("generated") else 0
        if mode == "raid":
            if b.get("role") == "healer":
                return (0, -(H.get(bid, {}).get("capacity") or 0), gen)
            r = R.get(bid) or {}
            return (0, -((r.get("value") if r.get("tank") else r.get("dps")) or 0), gen)
        if mode == "leveling":
            w = weighted(L.get(bid) or {})
            return (0 if w else 1, w or 0, gen)
        return (gen, b.get("tier") != "primary", bid)
    parse_ids = {b["id"] for b in builds if b["id"].endswith("-parse")}
    main = [b for b in builds if b["id"] not in parse_ids]
    return sorted(main, key=key) + [b for b in builds if b["id"] in parse_ids]


def link(cls, b, src):
    page = paths.build_page_by_id("forever", cls, b["id"])
    name = rs.display_name(cls, b)
    return f"[{name}]({paths.rel(src, page)})" if page else name


def tree_link(cls, b):
    return f"[open the talent tree]({rs.tf_link(cls, rs.flat(b))})"


def spec_title(cls, spec):
    return f"{spec} {cls.capitalize()}" if not spec.startswith("Hybrid") else f"{cls.capitalize()} hybrid: {spec.split(' ', 1)[1]}"


# ------------------------------------------------------------------------------------------------ pages
def mode_section(cls, spec, mode, builds, nums, src):
    """The body of one spec x mode page."""
    R, L, H = nums
    o = []
    ranked = rank_builds(cls, mode, builds, nums)
    if mode == "leveling" and not ranked:
        other = SM.LEVEL_AS.get((cls, spec))
        if other:
            o += [f"{spec} is a {'healing' if cls in SM.HEAL_TREES and spec in SM.HEAL_TREES[cls] else 'tanking'} spec: level as **{other}** "
                  f"([{other} leveling](../leveling/{SM.slug(other)}.md)) and switch your talents to {spec} at 60 (a respec at a class trainer).", ""]
        else:
            o += ["No leveling build for this spec yet.", ""]
        return o
    if not ranked:
        return ["No build for this spec in this mode yet.", ""]
    top = ranked[0]
    o += [f"**{link(cls, top, src)}** ({rs.split_of(cls, rs.flat(top))}) — {tree_link(cls, top)}", ""]
    if top.get("generated"):
        o += [f"> Generated build: no hand-made {spec} build exists for this mode yet, so this is the stats model's best {spec} build"
              + (", refined in the raid simulator" if mode == "raid" and (GEN.get(cls, {}).get(top["id"], {}).get("entry")) else "")
              + ". A starting point, not a proven build.", ""]
    if mode == "leveling":
        if top.get("order"):
            o += ["Talent order (one point per level from 10):", "", "| Levels | Talent | Points |", "|---|---|---|"]
            o += [f"| {s['levels']} | {s['talent']} ({s['tree']}) | {s['points']} |" for s in top["order"]]
            o.append("")
        spec_model = (GEN.get(cls, {}).get(top["id"], {}) or {}).get("model") or rs.leveling_pick(cls)[1]
        try:
            desc = rr.fl_description(cls, spec_model)
        except Exception:   # noqa: BLE001
            desc = ""
        if desc:
            o += ["**What to press:** " + " ".join(desc.split()), ""]
        per = L.get(top["id"])
        if per:
            o += ["| Level | Seconds per kill (same-level mobs, eating and drinking included) |", "|---|---|"]
            o += [f"| {Lv} | {v:.0f} |" for Lv, v in sorted(per.items())]
            o.append("")
    elif mode == "raid":
        if top.get("role") == "healer":
            h = H.get(top["id"])
            if h:
                o += [f"Healing capacity {h['capacity']:.2f} (the raid damage it heals through in this project's healer lab), {h['hps']:.0f} "
                      "healing per second. Healers are not in the community simulator.", ""]
        else:
            r = R.get(top["id"])
            if r and r.get("tank"):
                o += [f"Tank value {r['value']:.3f} (threat and damage taken under a boss, relative to our reference tank build).", ""]
            elif r:
                o += ["| Setting | DPS |", "|---|---|", f"| Training dummy (only your own buffs) | {r['dps']:.0f} |"]
                if r.get("raid"):
                    o.append(f"| Parse (a full raid: every raid buff and debuff) | {r['raid']:.0f} |")
                o.append("")
            if r:
                o += ["**What to press** (top to bottom: cast the first line that is ready):", ""] + rs.rotation_lines(r["d"], r["row"]) + [""]
        parse = next((b for b in ranked if b["id"].endswith("-parse")), None)
        if parse:
            o += [f"Parse build (personal damage in a full raid, where the raid brings the buffs): {link(cls, parse, src)} "
                  f"({rs.split_of(cls, rs.flat(parse))}) — {tree_link(cls, parse)}.", ""]
    else:
        o += [rs.short(top.get("summary"), 400), "",
              "PvP has no fixed rotation (it depends on the fight), and no simulator plays PvP: these builds rest on the talents' descriptions "
              "and the Classic community's PvP builds.", ""]
    alts = [b for b in ranked[1:] if not b["id"].endswith("-parse")]
    if alts:
        o += ["Other builds of this spec:", ""]
        for b in alts:
            extra = ""
            if mode == "raid" and (R.get(b["id"]) or {}).get("dps") and not (R.get(b["id"]) or {}).get("tank"):
                extra = f", {R[b['id']]['dps']:.0f} DPS on the dummy"
            if mode == "leveling" and weighted(L.get(b["id"]) or {}):
                extra = f", {weighted(L[b['id']]):.0f} s per kill (level-weighted)"
            o.append(f"- {link(cls, b, src)} ({rs.split_of(cls, rs.flat(b))}{extra}) — {tree_link(cls, b)}")
        o.append("")
    return o


def ranking(cls, g, specs, mode, nums, prefix=""):
    """One mode's specs, best first, as markdown lines. Leveling: level-weighted seconds per kill (fight lab, the same simulator for every
    spec, so specs compare). Raid: damage specs by training-dummy DPS, then tanks and healers (other jobs, their own measures). PvP: no
    simulator plays PvP, so it is a list, not a ranking."""
    R, L, H = nums
    rows = []
    for spec in specs:
        ranked = rank_builds(cls, mode, g[spec][mode], nums)
        if ranked:
            rows.append((spec, ranked[0]))
    page = lambda spec: f"{prefix}{SM.slug(spec)}.md"   # noqa: E731
    name = lambda spec, b: f"[{spec}]({page(spec)}) — {rs.display_name(cls, b)}" + (" (generated)" if b.get("generated") else "")   # noqa: E731
    o = []
    if mode == "leveling":
        scored = sorted(((weighted(L.get(b["id"]) or {}), spec, b) for spec, b in rows if weighted(L.get(b["id"]) or {})), key=lambda x: x[0])
        if not scored:
            return ["No leveling numbers yet.", ""]
        best = scored[0][0]
        o += ["Ranked by time per kill in the fight lab (levels 20-60, higher levels count more; lower is faster):", "",
              "| # | Spec and build | Seconds per kill | Behind the fastest |", "|---|---|---|---|"]
        o += [f"| {i} | {name(spec, b)} | {w:.0f} | {'fastest' if i == 1 else f'{w / best - 1:+.0%}'} |" for i, (w, spec, b) in enumerate(scored, 1)]
        lv = [spec for spec in specs if not g[spec][mode] and SM.LEVEL_AS.get((cls, spec))]
        if lv:
            o += ["", "Healing and tanking specs level as a damage spec and switch at 60: "
                  + ", ".join(f"{spec} levels as {SM.LEVEL_AS[(cls, spec)]}" for spec in lv) + "."]
        o.append("")
    elif mode == "raid":
        dps, tanks, heals = [], [], []
        for spec, b in rows:
            if b.get("role") == "healer":
                heals.append((-(H.get(b["id"], {}).get("capacity") or 0), spec, b))
            elif (R.get(b["id"]) or {}).get("tank"):
                tanks.append((spec, b))
            elif (R.get(b["id"]) or {}).get("dps"):
                dps.append((-R[b["id"]]["dps"], spec, b))
        if dps:
            dps.sort(key=lambda x: x[0])
            best = -dps[0][0]
            o += ["**Damage**, ranked by training-dummy DPS (only your own buffs; the parse column is the same build in a full raid):", "",
                  "| # | Spec and build | Dummy DPS | Parse DPS | Behind the best |", "|---|---|---|---|---|"]
            for i, (d, spec, b) in enumerate(dps, 1):
                r = R[b["id"]]
                o.append(f"| {i} | {name(spec, b)} | {-d:.0f} | {r['raid']:.0f} |" if r.get("raid") else f"| {i} | {name(spec, b)} | {-d:.0f} | - |")
                o[-1] += f" {'best' if i == 1 else f'{-d / best - 1:+.0%}'} |"
            o.append("")
        if tanks:
            o += ["**Tanking**: " + ", ".join(name(spec, b) for spec, b in tanks) + ".", ""]
        if heals:
            heals.sort(key=lambda x: x[0])
            o += ["**Healing**" + (" (ranked by the healer lab's capacity: the raid damage the healer keeps up with)" if len(heals) > 1 else "") + ": "
                  + ", ".join(name(spec, b) + (f" ({-c:.2f})" if len(heals) > 1 and c else "") for c, spec, b in heals) + ".", ""]
    else:
        o += ["Not ranked: no simulator plays PvP, so there is nothing fair to rank on. The builds below rest on the talents' descriptions "
              "and the community's PvP builds.", ""]
        o += [f"- {name(spec, b)}: {rs.split_of(cls, rs.flat(b))}" for spec, b in rows]
        o.append("")
    return o


def cell(cls, spec, mode, builds, nums, src):
    R, L, H = nums
    ranked = rank_builds(cls, mode, builds, nums)
    page = f"{mode}/{SM.slug(spec)}.md"
    if not ranked:
        other = SM.LEVEL_AS.get((cls, spec)) if mode == "leveling" else None
        return f"[level as {other}]({page})" if other else "-"
    top = ranked[0]
    note = ""
    if mode == "raid":
        if top.get("role") == "healer":
            note = "healer"
        else:
            r = R.get(top["id"]) or {}
            note = "tank" if r.get("tank") else (f"{r['dps']:.0f} DPS" if r.get("dps") else "")
    elif mode == "leveling":
        w = weighted(L.get(top["id"]) or {})
        note = f"{w:.0f} s/kill" if w else ""
    gen = " (generated)" if top.get("generated") else ""
    return f"[{rs.display_name(cls, top)}]({page}){gen}" + (f"<br>{note}" if note else "")


def class_pages(cls):
    B = rr.builds(cls)
    g = SM.grid(cls, list(B.values()))
    nums = (raid_numbers(cls), leveling_numbers(cls), healer_numbers(cls))
    specs = SM.trees(cls) + sorted(s for s in g if s.startswith("Hybrid") and any(g[s].values()))
    for mode in SM.MODES:
        d = ROOT / cls / mode
        d.mkdir(parents=True, exist_ok=True)
        for old in d.glob("*.md"):
            old.unlink()   # generated folder: pages of specs that no longer have builds go away
        for spec in specs:
            src = d / f"{SM.slug(spec)}.md"
            o = [f"# {spec_title(cls, spec)} — {SM.MODE_TITLE[mode]}", "",
                 f"[{cls.capitalize()}](../START-HERE.md) > [{SM.MODE_TITLE[mode]}](README.md) > {spec}", ""]
            o += mode_section(cls, spec, mode, g[spec][mode], nums, src)
            o += ["---", FOOT, ""]
            src.write_text("\n".join(o) + "\n", encoding="utf-8")
        idx = [f"# {cls.capitalize()} — {SM.MODE_TITLE[mode]}", "", f"[{cls.capitalize()}](../START-HERE.md) > {SM.MODE_TITLE[mode]}", ""]
        idx += ranking(cls, g, specs, mode, nums)
        idx += ["Differences under 2-3% are within the simulations' noise and assumptions: treat them as a tie.", "", "---", FOOT, ""]
        (d / "README.md").write_text("\n".join(idx) + "\n", encoding="utf-8")
    src = ROOT / cls / "START-HERE.md"
    intro = ""
    for line in (ROOT / cls / "README.md").read_text(encoding="utf-8").splitlines():
        if line.startswith("> "):
            intro += line[2:] + " "
        elif intro:
            break
    o = [f"# {cls.capitalize()}: start here", "", "[All classes](../START-HERE.md)", ""]
    if intro:
        o += [intro.strip(), ""]
    o += ["Pick what you want to do (the columns) and the spec you want to play (the rows). Every link opens a page with the talents "
          "(and a link that shows them in a talent calculator), what to press, and the numbers behind the choice.", "",
          "| Spec | Leveling | Raid (training dummy / parse) | PvP |", "|---|---|---|---|"]
    for spec in specs:
        o.append(f"| **{spec}** | " + " | ".join(cell(cls, spec, m, g[spec][m], nums, src) for m in SM.MODES) + " |")
    o += ["", "## Which spec is best?", ""]
    for m in SM.MODES:
        o += [f"### {SM.MODE_TITLE[m]}", ""] + ranking(cls, g, specs, m, nums, prefix=f"{m}/")
    o += ["Differences under 2-3% are within the simulations' noise and assumptions: treat them as a tie.", ""]
    o += ["", "Hybrids spend their points across two trees (no tree reaches 30 points, or the build is made for a spell that needs both).", "",
          f"How the class works and what changed in Forever: [README.md](README.md). Every report, simulation and data file: [research/](research/).", "",
          "---", FOOT, ""]
    src.write_text("\n".join(o) + "\n", encoding="utf-8")
    best_lvl = min(((weighted(nums[1].get(b["id"]) or {}) or 1e9, b) for b in B.values() if SM.mode_of(b) == "leveling"), key=lambda x: x[0], default=(None, None))[1]
    best_raid = max((((nums[0].get(b["id"]) or {}).get("dps") or 0, b) for b in B.values() if SM.mode_of(b) == "raid" and not (nums[0].get(b["id"]) or {}).get("tank")), key=lambda x: x[0])
    return {"cls": cls, "lvl": best_lvl, "raid": best_raid}


def root_page(infos):
    o = ["# WoW: Forever class guides — start here", "",
         "This project works out the best talents and the best way to play every class in **World of Warcraft: Forever** (the Classic+ "
         "release, launching 2026-11-04), from the beta's talent trees and simulations: the community's combat simulator for raids and this "
         "project's own simulators for leveling and healing.", "",
         "Pick your class. Each class page is a grid: its three specs (and hybrids) against the three modes (leveling, raid, PvP).", "",
         "| Class | Fastest leveling | Most raid damage (training dummy) |", "|---|---|---|"]
    for i in infos:
        cls = i["cls"]
        lvl = rs.display_name(cls, i["lvl"]) if i["lvl"] else "-"
        dps, b = i["raid"]
        o.append(f"| [{cls.capitalize()}]({cls}/START-HERE.md) | {lvl} | {rs.display_name(cls, b)} ({dps:.0f} DPS) |")
    o += ["", "## How to read the numbers", "",
          "- **Training dummy DPS**: your own damage against a raid boss with only the buffs you bring yourself; it ranks builds fairly.",
          "- **Parse DPS**: the same in a full raid, with every raid buff and debuff: your personal damage in a real raid.",
          "- **Seconds per kill** (leveling): a whole kill cycle against same-level mobs, including eating and drinking.",
          "- Everything is a simulation of the beta, not a measurement in the game. Treat differences under 2-3% as a tie.", "",
          "## Everything else", "",
          "- [README.md](README.md): how the project works.",
          "- [_reference/](_reference/): cross-class reports (simulator summaries, the talentsforever.com comparison, launch checklists).", "",
          "---", FOOT, ""]
    (ROOT / "START-HERE.md").write_text("\n".join(o) + "\n", encoding="utf-8")


def main():
    classes = [c for c in sys.argv[1:] if c in SM.CLASSES] or SM.CLASSES
    infos = [class_pages(c) for c in classes]
    for i in infos:
        print(f"{i['cls']}: START-HERE.md and {len(SM.MODES)} mode folders written")
    if classes == SM.CLASSES:
        root_page(infos)
        print("wrote START-HERE.md")


if __name__ == "__main__":
    main()
