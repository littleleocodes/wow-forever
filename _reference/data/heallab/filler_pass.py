"""Healer filler pass (2026-11-08, user: "the resto druid talent spec says to take Improved Wrath. Why would that ever be a thing? Theres
not a single other better place to spend that talent? Check thinks like that constantly"; page-audit O2-O3, page-audit-1108 S8).

The deep healer searches score every point the healer lab measures at zero alike, so a spare point lands on any talent that reads zero:
a Restoration druid's Improved Wrath and Furor, a Holy paladin's Divine Strength. This pass, for one healer build:

1. measures every talent's value by removal (one rank less and, for a multi-rank talent, every rank; common random numbers; the
   tail-mean capacity the lab ranks on);
2. collects the zero points: a talent whose removal costs less than the noise floor in the five-minute fight and in a ten-minute one
   (DURATION 600: the five-minute fight leaves a healer that does not run dry with every mana talent at zero), removable while the
   build stays legal (validate_builds.check_state: tier gating and prerequisites);
3. tries every legal one-point move of a zero point into a talent a healer could want and keeps the best when it gains --bar (0.5%) and
   two standard errors, again on fresh seeds, and loses no more than two standard errors in the long fight; then starts over (a talent
   the lab did not model, Bloom until 2026-11-08, is found here once it is modelled);
4. moves the zero points left to the healer's utility the lab does not model: pushback protection first ("lose casting time"), then
   threat reduction of the healer's spells ("threat generated by your spells"; one-spell threat cuts and "causes no threat" are no
   utility). The build may lose no more than two standard errors against the capacity the pass started from, in either fight, so small
   losses cannot add up. A point that finds neither stays where it is.

Fixes of 2026-11-09 (the first passes): a talent that is already pushback or threat utility is no zero point (Healing Focus had gone to
Natural Grace); one-rank losses under the floor added up to -1.9% for the Restoration druid (Improved Regrowth, Heart of the Wild: now
the every-rank removal and the start bound); Holy Nova and Holy Binding had counted as threat reduction ("cause no threat"); a one-rank
destination the lab does not simulate is an ability nobody casts; a talent that teaches a spell the lab casts and a module's KEEP talent
(Totemic Focus: the lab charges one totem) are no zero points.

    python _reference/data/heallab/filler_pass.py <class> --build <id> [--runs 200] [--jobs 8] [--write]

Record `heallab/filler/<class>-<build>.json`; `--write` applies the moves to proposed-builds.json with a note. Re-race the class's healer
builds afterwards (heallab/run.py) and regenerate the pages. The healer lab is a model of stated assumptions (heallab/tables.py).
"""
import argparse
import datetime
import importlib
import json
import math
import multiprocessing
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent))
import heal_worker as W  # noqa: E402
import validate_builds as VB  # noqa: E402

OUT = HERE / "filler"
STD = {}
LONG = {"DURATION": 600.0}
PUSHBACK = re.compile(r"lose casting time|lose no casting time|pushback", re.I)
THREAT = re.compile(r"threat generated by your [\w ,]*spells", re.I)
# a destination a healer could want: healing, mana, casting, crit, the stats heals scale with, pushback or threat (2026-11-08: trying every
# talent cost hours of lab time on damage talents a move to which can only read 0)
RELEVANT = re.compile(r"heal|mana|spirit|intellect|critical|cast|threat|pushback|interrupt|absorb|shield", re.I)


def talent_data(cls):
    d = json.load(open(HERE.parent / "forever-talents" / f"{cls}.json", encoding="utf-8"))
    out = {}
    for tr in d["trees"]:
        for t in tr["talents"]:
            r = (t.get("ranks") or [""])[-1]
            out[t["name"]] = (r if isinstance(r, str) else (r.get("text") or ""), t.get("maxRank") or len(t.get("ranks") or []))
    return out


def by_tree(trees, flat):
    out = {t: {} for t in trees}
    for n, r in flat.items():
        for t, tr in trees.items():
            if n in tr["talents"]:
                out[t][n] = r
                break
    return out


def legal(trees, flat):
    errors = []
    VB.check_state(trees, by_tree(trees, {n: r for n, r in flat.items() if r}), "x", errors)
    return not errors


def caps(pool, cls, allocs, seeds, steps, over=STD):
    return pool.map(W.capacity_with, [(cls, {n: r for n, r in a.items() if r}, seeds, steps, over) for a in allocs], chunksize=1)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cls")
    ap.add_argument("--build", required=True)
    ap.add_argument("--runs", type=int, default=200)
    ap.add_argument("--steps", type=int, default=10)
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--bar", type=float, default=0.005)
    ap.add_argument("--max-moves", type=int, default=8)
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    cls = a.cls
    path = ROOT / cls / "research/talents/forever/proposed-builds.json"
    data = json.load(open(path, encoding="utf-8"))
    b = next(x for x in data["builds"] if x["id"] == a.build)
    trees = VB.load_forever()[cls]
    names = [n for t in trees.values() for n in t["talents"]]
    cap_of = {n: t["talents"][n]["max"] for t in trees.values() for n in t["talents"]}
    tips = talent_data(cls)
    H = importlib.import_module(W.CLASSES[cls]).Healer
    simulated = set(getattr(H, "SIMULATED", set()))
    # never zero points: a talent that teaches a spell the lab casts (Riptide, Swiftmend, Nature's Swiftness: its worth is the heal
    # policy's use of it, and the spec plays its signature spells) and the module's KEEP (raid value the lab leaves out: Totemic Focus)
    keep = set(getattr(H, "TALENT_SPELLS", {}).values()) | set(getattr(H, "KEEP", {}))
    tip = lambda n: tips.get(n, ("", 0))[0]  # noqa: E731
    utility = lambda n: bool(PUSHBACK.search(tip(n)) or THREAT.search(tip(n))) or n in keep  # noqa: E731
    cur = {n: r for items in b["allocation"].values() for n, r in items if r}
    seeds = list(range(5000, 5000 + a.runs))
    fresh = list(range(9000, 9000 + a.runs))
    moves, rec = [], {"class": cls, "build": a.build, "date": datetime.date.today().isoformat(), "runs": a.runs, "long": LONG, "steps": []}
    with multiprocessing.Pool(a.jobs, initializer=W.init, initargs=(cls,)) as pool:
        (s_base, s_spread), (l_base, l_spread) = caps(pool, cls, [cur], seeds, a.steps)[0], caps(pool, cls, [cur], seeds, a.steps, LONG)[0]
        start = {"std": s_base, "std_se": s_spread / math.sqrt(len(seeds)), "long": l_base, "long_se": l_spread / math.sqrt(len(seeds))}
        rec["start"] = {k: round(v, 4) for k, v in start.items()}
        print(f"start: capacity {s_base:.4f} (se {start['std_se']:.4f}); ten-minute fight {l_base:.4f} (se {start['long_se']:.4f})", flush=True)
        for _ in range(a.max_moves):
            base, spread = caps(pool, cls, [cur], seeds, a.steps)[0]
            se = spread / math.sqrt(len(seeds))
            held = sorted(cur)
            # one rank less, and every rank of a multi-rank talent (losses under the floor one rank at a time add up)
            rem = {n: [dict(cur, **{n: cur[n] - 1})] for n in held}
            for n in held:
                if cur[n] > 1 and legal(trees, dict(cur, **{n: 0})):
                    rem[n].append(dict(cur, **{n: 0}))
            flat = [(n, x) for n in held for x in rem[n]]
            res = caps(pool, cls, [x for _, x in flat], seeds, a.steps)
            value = {}
            for (n, _), (c, _) in zip(flat, res):
                value[n] = max(value.get(n, -1e9), base - c)
            floor = max(2 * se, 0.001 * base)
            moved_from = {m["from"] for m in moves}
            cand_zero = [n for n in held if value[n] <= floor and legal(trees, dict(cur, **{n: cur[n] - 1})) and not utility(n)]
            # the same in the ten-minute fight, for the talents that read zero in the five-minute one
            flat_l = [(n, x) for n in cand_zero for x in rem[n]]
            l_base, l_spread = caps(pool, cls, [cur], seeds, a.steps, LONG)[0]
            l_se = l_spread / math.sqrt(len(seeds))
            res_l = caps(pool, cls, [x for _, x in flat_l], seeds, a.steps, LONG)
            value_l = {}
            for (n, _), (c, _) in zip(flat_l, res_l):
                value_l[n] = max(value_l.get(n, -1e9), l_base - c)
            floor_l = max(2 * l_se, 0.001 * l_base)
            zero = [n for n in cand_zero if value_l[n] <= floor_l]
            mana_only = [n for n in cand_zero if n not in zero]
            print(f"capacity {base:.4f} (se {se:.4f}); zero points: {', '.join(zero) or 'none'}"
                  + (f"; worth something only in the ten-minute fight: {', '.join(mana_only)}" if mana_only else ""), flush=True)
            rec["steps"].append({"capacity": round(base, 4), "se": round(se, 4), "long": round(l_base, 4), "long_se": round(l_se, 4),
                                 "values": {n: round(v, 4) for n, v in value.items()}, "values_long": {n: round(v, 4) for n, v in value_l.items()},
                                 "zero": zero, "long_only": mana_only})
            if not zero:
                break
            cand = []
            for z in zero:
                for d in names:
                    if d == z or d in moved_from or cur.get(d, 0) >= cap_of[d] or not RELEVANT.search(tip(d)):
                        continue
                    if tips.get(d, ("", 0))[1] == 1 and d not in simulated:
                        continue   # a one-rank talent the lab does not simulate: an ability the healer never casts (Holy Nova)
                    alloc = dict(cur, **{z: cur[z] - 1, d: cur.get(d, 0) + 1})
                    if legal(trees, alloc):
                        cand.append((z, d, alloc))
            res = caps(pool, cls, [c[2] for c in cand], seeds, a.steps)
            ranked = sorted(((c, r[0]) for c, r in zip(cand, res)), key=lambda x: -x[1])
            done = False
            for (z, d, alloc), c in ranked[:3]:
                if not (c >= base * (1 + a.bar) and c - base >= 2 * se):
                    break
                (fc_new, _), (fc_old, _) = caps(pool, cls, [alloc, cur], fresh, a.steps)
                (lc, _), = caps(pool, cls, [alloc], seeds, a.steps, LONG)
                ok = fc_new >= fc_old * (1 + a.bar) and lc >= l_base - 2 * l_se
                print(f"  try {z} -> {d}: {base:.4f} -> {c:.4f} ({c / base - 1:+.2%}); fresh seeds {fc_new / fc_old - 1:+.2%}; "
                      f"ten-minute fight {lc / l_base - 1:+.2%}: {'kept' if ok else 'not kept'}", flush=True)
                if ok:
                    moves.append({"from": z, "to": d, "capacity": round(c, 4), "gain": round(c / base - 1, 4), "fresh": round(fc_new / fc_old - 1, 4),
                                  "long": round(lc / l_base - 1, 4), "why": "measured"})
                    cur = {n: r for n, r in alloc.items() if r}
                    done = True
                    break
            if done:
                continue
            # no measured gain: the zero points go to what a raid healer wants and the lab does not model, while the build stays within
            # two standard errors of where the pass started, in both fights
            util = []
            for (z, d, alloc), (c, _) in zip(cand, res):
                kind = 0 if PUSHBACK.search(tip(d)) else 1 if THREAT.search(tip(d)) else None
                if kind is not None and c >= start["std"] - 2 * start["std_se"]:
                    util.append((kind, -c, z, d, alloc, c))
            done = False
            for kind, _, z, d, alloc, c in sorted(util)[:4]:
                (lc, _), = caps(pool, cls, [alloc], seeds, a.steps, LONG)
                if lc < start["long"] - 2 * start["long_se"]:
                    print(f"  {z} -> {d}: the ten-minute fight falls to {lc:.4f} (start {start['long']:.4f}): not kept", flush=True)
                    continue
                moves.append({"from": z, "to": d, "capacity": round(c, 4), "gain": round(c / base - 1, 4), "long": round(lc / l_base - 1, 4),
                              "why": "pushback protection" if kind == 0 else "threat reduction"})
                print(f"  move {z} -> {d} ({moves[-1]['why']}, not modelled): {base:.4f} -> {c:.4f}; ten-minute fight {lc:.4f}", flush=True)
                cur = {n: r for n, r in alloc.items() if r}
                done = True
                break
            if not done:
                break
        (e_std, _), (e_long, _) = caps(pool, cls, [cur], seeds, a.steps)[0], caps(pool, cls, [cur], seeds, a.steps, LONG)[0]
        rec["end"] = {"std": round(e_std, 4), "long": round(e_long, 4)}
        print(f"end: capacity {e_std:.4f} ({e_std / start['std'] - 1:+.2%}); ten-minute fight {e_long:.4f} ({e_long / start['long'] - 1:+.2%})", flush=True)
    rec["moves"] = moves
    rec["final"] = cur
    OUT.mkdir(exist_ok=True)
    (OUT / f"{cls}-{a.build}.json").write_text(json.dumps(rec, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps(moves, indent=1))
    if a.write and moves:
        b["allocation"] = {t: [[n, r] for n, r in by_tree(trees, cur)[t].items() if r] for t in b["allocation"]}
        text = "; ".join(f"{m['from']} to {m['to']} ({m['why']}, capacity {m['gain']:+.1%})" for m in moves)
        b.setdefault("notes", []).insert(0, f"{rec['date']}: healer filler pass (heallab/filler_pass.py, {a.runs} runs, checked in a ten-minute "
                                            f"fight too): points the healer lab measures at zero moved: {text}.")
        path.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
