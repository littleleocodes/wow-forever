"""What the gear night of 2026-11-18 changed in the gear sets (user, 2026-11-19: "is the new gear sets committed and pushed to GitHub
so I can look at them?"): every set file that differs from a git revision, item by item, with the removed items the game holds back for
a later phase marked (gear_opt.later_phase: the simulator database's phase 2 outside Molten Core and Onyxia).

    python _reference/data/raidsim/gear_phase_report.py [--since 10107bae] [--write]

Reads the set files under raidsim/gear_sets/forever/ (the standard sets the races use and the tier sets the pages show) as they are on
disk, so a run during the gear night lists the sets made so far. Writes _reference/gear-phase-changes.md (generated).
"""
import argparse
import datetime
import json
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
DATA = HERE.parent
ROOT = DATA.parents[1]
sys.path[:0] = [str(HERE), str(DATA)]
import gear_opt as G  # noqa: E402
import setup  # noqa: E402

SETS = "_reference/data/raidsim/gear_sets/forever"
OUT = ROOT / "_reference" / "gear-phase-changes.md"
SLOTS = ["Head", "Neck", "Shoulders", "Back", "Chest", "Wrist", "Hands", "Waist", "Legs", "Feet", "Finger", "Finger", "Trinket",
         "Trinket", "Main hand", "Off hand", "Ranged/relic"]
TIER = {"bis": "Raid BiS", "prebis": "Pre-BiS", "dungeon": "Quests and dungeons"}
CLASSES = ["druid", "hunter", "mage", "paladin", "priest", "rogue", "shaman", "warlock", "warrior"]


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, encoding="utf-8").stdout


def items_of(text):
    try:
        its = json.loads(text)["items"]
    except (ValueError, KeyError, TypeError):
        return None
    return [(x or {}).get("id") for x in its] + [None] * (17 - len(its))


def label(path, users):
    name = pathlib.PurePosixPath(path).name.replace(".gear.json", "")
    if "/tiers/" in path:
        cls = name.split("-", 1)[0]
        rest = name[len(cls) + 1:]
        tier = rest.rsplit("-", 1)[-1]
        spec = rest[: -len(tier) - 1].replace("-", " ")
        role = ""
        if spec.endswith(" tank"):
            spec, role = spec[:-5], " (tank)"
        elif spec.endswith(" heal"):
            spec, role = spec[:-5], " (healer)"
        return cls, f"{spec.title()}{role}: {TIER.get(tier, tier)}"
    cls = name.split("-", 1)[0]
    who = ", ".join(users.get(path, [])) or "no entry"
    return cls, f"Standard set ({who}), the set every race of those entries uses"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--since", default="10107bae", help="the revision before the gear night (default: the PvP pages commit)")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    db, zones = G.load_db(setup.checkout())
    specs = json.load(open(DATA / "raidsim" / "specs.json", encoding="utf-8"))
    users = {}
    for cls, es in specs.items():
        if not isinstance(es, dict):   # the file's notes ("_about" and the like)
            continue
        for en, e in es.items():
            if isinstance(e, dict) and e.get("gear"):
                users.setdefault(e["gear"].replace("\\", "/"), []).append(en)
    changed = [p for p in git("diff", "--name-only", a.since, "--", SETS).splitlines() if p.endswith(".gear.json")]
    changed += [p for p in git("ls-files", "--others", "--exclude-standard", "--", SETS).splitlines() if p.endswith(".gear.json")]
    rows = {}
    later_total = 0
    for p in sorted(set(changed)):
        old = items_of(git("show", f"{a.since}:{p}"))
        cur = (ROOT / p)
        new = items_of(cur.read_text(encoding="utf-8")) if cur.exists() else None
        if new is None:
            continue
        cls, lab = label(p, users)
        diffs = []
        for s in range(17):
            o, n = (old or [None] * 17)[s], new[s]
            if o == n:
                continue
            on = G.item_name(db, o) if o else "(empty)"
            late = bool(o and o in db and G.later_phase(db[o], zones))
            later_total += late
            diffs.append(f"{SLOTS[s]}: {on}{' (later phase)' if late else ''} -> {G.item_name(db, n) if n else '(empty)'}")
        if diffs:
            rows.setdefault(cls, []).append((lab, pathlib.PurePosixPath(p).name, diffs, old is None))
    n = sum(len(v) for v in rows.values())
    o = ["# Gear sets changed by the phase rule (generated)", "",
         f"> Generated by `_reference/data/raidsim/gear_phase_report.py` on {datetime.date.today().isoformat()}: every gear set that differs "
         f"from `{a.since}` (before the gear night of 2026-11-18), item by item. **(later phase)** marks a removed item the game holds back "
         "for a later phase (the simulator database's phase 2 outside Molten Core and Onyxia: the Silithus war's quest rewards, later raids' "
         "crafts, rank-14 PvP gear). Sets the night has not reached yet are not listed. The raid pages show the new sets when the night's "
         "last step rebuilds them. Do not hand-edit.", "",
         f"{n} sets changed; {later_total} later-phase items removed.", ""]
    for cls in CLASSES:
        if cls not in rows:
            continue
        o += [f"## {cls.capitalize()}", ""]
        for lab, fname, diffs, new_file in sorted(rows[cls]):
            o += [f"**{lab}** (`{fname}`{', new' if new_file else ''}):", ""] + [f"- {d}" for d in diffs] + [""]
    text = "\n".join(o) + "\n"
    if a.write:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT).as_posix()}: {n} sets, {later_total} later-phase items removed")
    else:
        print(text)


if __name__ == "__main__":
    main()
