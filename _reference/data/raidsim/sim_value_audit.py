"""Talent numbers the simulator uses against the beta's tooltips (2026-10-05, user request: a standard step after every beta refresh;
2026-10-03: Lightning Reflexes read 2% Agility a rank in game while the simulator's curve still said 3%).

    python _reference/data/raidsim/sim_value_audit.py [classes] [--write]

For every multi-rank talent the simulator reads as a trait curve (spells_auto_gen.go `generatedCurves`, the per-rank values the fork's
`spelldata.Talent` ladders apply), the numbers that change between rank 1 and the top rank of our tooltips (forever-talents/<class>.json,
the refreshed beta text) are matched against the curve's first and last values (as given, a tenth or a thousandth: the client states
times in milliseconds and some percents in tenths; 2% or half a point of rounding allowed, since tooltips round a rank's value). A talent
none of whose curve rows matches is listed. Most listings are unit or wording artefacts (yards, durations, a second effect the tooltip
does not state); damage, crit, haste, stat and cost talents in a list are the ones to check and, if the simulator is behind the beta,
to patch (raidsim/patches/, e.g. Lightning Reflexes). PATCHED names the talents a patch already corrects.
--write: _reference/sim-value-audit.md (generated). Run it after refresh_forever_talents.py and every simulator update.
"""
import argparse
import datetime
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
import sys  # noqa: E402
sys.path.insert(0, str(HERE))
import setup as SETUP  # noqa: E402
SIM = SETUP.checkout() / "sim"   # the official wowsims/forever clone since 2026-10-22 (the fork's forever-repo before); same generatedCurves format
PAGE = ROOT / "_reference" / "sim-value-audit.md"
CLASSES = ("warrior", "paladin", "hunter", "rogue", "priest", "shaman", "mage", "warlock", "druid")
PATCHED = {("paladin", "Champion of the Light"): "patches/forever edits.json: 10/20/30% of Intellect (70425 tooltip; user decision 2026-10-18)"}   # Lightning Reflexes retired 2026-10-18: the official curve reads 2% a rank
TODAY = datetime.date.today().isoformat()


def curves():
    src = (SIM / "core" / "spelldata" / "spells_auto_gen.go").read_text(encoding="utf-8")
    blk = src[src.index("var generatedCurves"):]
    blk = blk[:blk.index("\n}\n")]
    out = {}
    for m in re.finditer(r"^\t(\d+):\s+\{(.*)\},?$", blk, re.M):
        rows = re.findall(r"\{([^{}]*)\}", m.group(2))
        out[int(m.group(1))] = [[float(x) for x in r.split(",") if x.strip()] for r in rows]
    return out


def audit(classes):
    cur = curves()
    camel = lambda n: re.sub(r"[^A-Za-z0-9]", "", n.replace("'", "").title())   # noqa: E731
    num = lambda s: [float(x) for x in re.findall(r"(?<![\w.])(\d+(?:\.\d+)?)", s)]   # noqa: E731
    rows, checked = [], 0
    for cls in classes:
        sd = (SIM / cls / "spell_data_auto_gen.go").read_text(encoding="utf-8")
        tal = {m.group(1): int(m.group(2)) for m in re.finditer(r"(\w+):\s+spelldata\.Talent\((\d+), (\d+)\)", sd)}
        data = json.load(open(ROOT / "_reference/data/forever-talents" / f"{cls}.json", encoding="utf-8"))
        for tr in data["trees"]:
            for t in tr["talents"]:
                sid = tal.get(camel(t["name"]))
                c = cur.get(sid) if sid else None
                if not c or len(t["ranks"]) < 2:
                    continue
                texts = [r if isinstance(r, str) else r.get("text", "") for r in t["ranks"]]
                n1, nm = num(texts[0]), num(texts[-1])
                varying = [(a, b) for a, b in zip(n1, nm) if a != b] if len(n1) == len(nm) else []
                if not varying:
                    continue
                checked += 1
                ends = [(abs(r[0]), abs(r[-1])) for r in c]

                def match(a, b):
                    return any(abs(r0 * f - a) <= max(0.51, a * 0.02) and abs(r1 * f - b) <= max(0.51, b * 0.02)
                               for r0, r1 in ends for f in (1, 0.1, 0.001))
                miss = [(a, b) for a, b in varying if not match(a, b)]
                if miss:
                    rows.append({"class": cls, "tree": tr["name"], "talent": t["name"], "spell": sid, "tooltip": varying, "curve": ends,
                                 "patched": PATCHED.get((cls, t["name"]))})
    return rows, checked


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("classes", nargs="*")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    rows, checked = audit(a.classes or CLASSES)
    build = json.load(open(ROOT / "_reference/data/forever-talents" / "hunter.json", encoding="utf-8")).get("build", "?")
    o = ["# Simulator talent numbers against the beta's tooltips (generated)", "",
         f"> Generated by `_reference/data/raidsim/sim_value_audit.py` on {TODAY}: our talent data (client build {build}) against the "
         "simulator's per-rank curves. Do not hand-edit.", "",
         f"{checked} multi-rank talents with numbers that change by rank were checked; {len(rows)} have a tooltip number no curve row matches. "
         "Most are units or wording (milliseconds, yards, a second effect); a damage, crit, haste, stat or cost talent here means the simulator "
         "applies an older value: patch it (raidsim/patches/) until the simulator catches up.", "",
         "| Class | Talent | Tooltip, rank 1 -> top | Simulator curve, rank 1 -> top | Patched |", "|---|---|---|---|---|"]
    for r in rows:
        o.append(f"| {r['class']} | {r['talent']} ({r['tree']}) | " + ", ".join(f"{x:g} -> {y:g}" for x, y in r["tooltip"]) + " | "
                 + ", ".join(f"{x:g} -> {y:g}" for x, y in r["curve"]) + f" | {r['patched'] or '-'} |")
    print(f"{checked} talents checked, {len(rows)} listed ({sum(1 for r in rows if r['patched'])} patched)")
    for r in rows:
        print(f"  {r['class']:8} {r['talent'][:28]:28} tooltip {r['tooltip']} | curve {r['curve']}" + (" [patched]" if r["patched"] else ""))
    if a.write:
        PAGE.write_text("\n".join(o) + "\n", encoding="utf-8")
        print(f"wrote {PAGE.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
