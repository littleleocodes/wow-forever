"""Write the simulator patch that fills the item armor the fork's database lacks (2026-10-15, user decision: "Fill it").

    python _reference/data/raidsim/fill_armor.py      # writes patches/forever/sim/core/forever_armor.go, then rebuild the bench

The fork's item database (2ce8265) lists base armor for about one armor item in five (1,338 of 7,277: Legplates of Wrath 749; none for
Lionheart Helm, the PvP and Forever items, most dungeon pieces), and the simulator gives an item no armor it does not list, so every tank
number undervalued armor and gear chosen in it favoured the items that list it (raidsim/tank_gear.py found it, 2026-10-15). The patch adds,
at database load, the armor of every armor item that lists none: its Classic 1.12 armor (cmangos classic-db dump, by item id), or for
Forever's new items a linear fit of Classic armor on item level per slot, armor type and quality (tank_gear.ClassicArmor). It goes into
stat 31 (BonusArmor), where the database keeps the armor it does list (Bear Form multiplies it). Our assumption: Forever may have
changed some armor values. Damage specs do not move (the boss attacks the tank); tank numbers do.
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path[:0] = [str(HERE), str(HERE.parent)]
import tank_gear as TG  # noqa: E402

DB = pathlib.Path.home() / ".wow-forever-tools" / "forever-repo" / "assets" / "database" / "db.json"
OUT = HERE / "patches" / "forever" / "sim" / "core" / "forever_armor.go"


def main():
    db = json.load(open(DB, encoding="utf-8"))
    ca = TG.ClassicArmor()
    rows = sorted((it["id"], ca.missing(it)) for it in db["items"])
    rows = [(i, a) for i, a in rows if a > 0]
    o = ["//go:build with_db", "", "// wow-forever patch (generated by _reference/data/raidsim/fill_armor.py; patches/README.md): the base armor of",
         "// the armor items the fork's database lists none for, from Classic 1.12 (cmangos classic-db) or a fit by item level for",
         "// Forever's new items. Added at load into stat 31 (BonusArmor), where the database keeps the armor it lists.",
         "package core", "", 'import "github.com/wowsims/forever/sim/core/proto"', "",
         "var foreverMissingArmor = map[int32]float64{"]
    line = []
    for i, a in rows:
        line.append(f"{i}: {a}")
        if len(line) == 8:
            o.append("\t" + ", ".join(line) + ",")
            line = []
    if line:
        o.append("\t" + ", ".join(line) + ",")
    o += ["}", "",
          "func foreverFillArmor(items []*proto.SimItem) {",
          "\tfor _, it := range items {",
          "\t\ta, ok := foreverMissingArmor[it.Id]",
          "\t\tif !ok {",
          "\t\t\tcontinue",
          "\t\t}",
          "\t\tfor _, so := range it.ScalingOptions {",
          "\t\t\tif so == nil {",
          "\t\t\t\tcontinue",
          "\t\t\t}",
          "\t\t\tif so.Stats == nil {",
          "\t\t\t\tso.Stats = map[int32]float64{}",
          "\t\t\t}",
          "\t\t\tif so.Stats[int32(proto.Stat_StatArmor)] == 0 && so.Stats[int32(proto.Stat_StatBonusArmor)] == 0 {",
          "\t\t\t\tso.Stats[int32(proto.Stat_StatBonusArmor)] = a",
          "\t\t\t}",
          "\t\t}",
          "\t}",
          "}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(o), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(HERE.parents[2])}: {len(rows)} items")


if __name__ == "__main__":
    main()
