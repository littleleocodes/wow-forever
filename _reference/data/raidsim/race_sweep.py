"""Best race per raid spec (2026-09-29, the overnight audit: "make sure our builds are the most optimal with what is available").

    python _reference/data/raidsim/race_sweep.py [classes] [--iterations 20000]

Forever reworked the racials (Orc Blood Fury is attack power and spell power, Axe Specialization is crit, the two Skyborne races are
new, Undead paladins and Orc mages exist) and the community simulator implements them (sim/core/racials.go). Every raid entry of
raidsim/specs.json runs a spec with one fixed race (`race`). This races each entry's best build of ours (its report's top row) under
every race the class can be, from talentsforever.com's racial list (popular_builds' archive has no racials; the site's data.json does:
raw/<date>-talentsforever-popular/data.json when present, else the list below), in the ranking setting (training dummy; tanks: raid,
tank value) and the raid setting, seeds 1 and 2. Writes `_reference/data/race-sweep.json` and `_reference/race-sweep.md` (generated).
Changing an entry's race is a separate decision: gear presets and weapon types interact with weapon racials.
"""
import argparse
import datetime
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "_reference/data"))
import run  # noqa: E402

OUT_JSON = ROOT / "_reference/data/race-sweep.json"
OUT_MD = ROOT / "_reference/race-sweep.md"
# talentsforever.com's racial list (data.json, 2026-09-26): which classes each race can be
RACES = {"Orc": ["warrior", "hunter", "rogue", "shaman", "mage", "warlock"],
         "Undead": ["warrior", "paladin", "rogue", "priest", "mage", "warlock"],
         "Tauren": ["warrior", "hunter", "shaman", "druid"],
         "Troll": ["warrior", "hunter", "rogue", "priest", "shaman", "mage", "warlock"],
         "WindshaperSkyborne": ["warrior", "hunter", "rogue", "shaman", "druid"],
         "Human": ["warrior", "paladin", "hunter", "rogue", "priest", "mage", "warlock"],
         "Dwarf": ["warrior", "paladin", "hunter", "rogue", "priest", "shaman"],
         "NightElf": ["warrior", "hunter", "rogue", "priest", "druid"],
         "Gnome": ["warrior", "rogue", "priest", "mage", "warlock"],
         "HighOrderSkyborne": ["warrior", "hunter", "rogue", "mage", "druid"]}
LABEL = {"WindshaperSkyborne": "Skyborne (Windshaper)", "HighOrderSkyborne": "Skyborne (High Order)", "NightElf": "Night Elf"}


def best_build(cls, spec):
    rep = run.paths.raidsim_dir(cls) / f"{spec}.json"
    if not rep.exists():
        return None
    rows = [x for x in json.load(open(rep, encoding="utf-8"))["results"] if x.get("ours") and not x.get("removal") and not x["label"].startswith("cand-")]
    key = (lambda x: x.get("value") or 0) if any(x.get("value") is not None for x in rows) else (lambda x: x.get("dps") or 0)
    rows.sort(key=lambda x: -key(x))
    return rows[0]["label"] if rows else None


def sweep(cls, spec, a, repo):
    entry = run.SPECS[cls][spec]
    bid = best_build(cls, spec)
    if not bid:
        return None
    tank = bool(entry.get("tank"))
    out = {"build": bid, "current": entry.get("race", "RaceHuman").replace("Race", ""), "tank": tank, "races": {}}
    for race, classes in RACES.items():
        if cls not in classes:
            continue
        run.SPECS[cls][spec] = dict(entry, race=f"Race{race}")
        for setting in (["raid"] if tank else ["dummy", "raid"]):
            run.SETTING_OVERRIDE = setting
            vals = []
            for seed in (1, 2):
                r = run.run_spec(cls, spec, argparse.Namespace(builds=[bid], iterations=a.iterations, duration=run.FIGHT, seed=seed, no_presets=True,
                                                               deltas=None, write=False), repo)["results"][0]
                vals.append(r.get("value") if tank else r["dps"])
            out["races"].setdefault(race, {})[setting] = sum(vals) / len(vals)
    run.SPECS[cls][spec] = entry
    return out


def render(res):
    o = ["# Best race per raid spec", "",
         f"> Generated by `_reference/data/raidsim/race_sweep.py` on {res['date']}: each raid spec's best build of ours under every race its "
         "class can be in Forever (talentsforever.com's racial list), in the community simulator with its Forever racials, mean of two "
         "seeds, 20,000 iterations each. Tanks: tank value in the raid setting (relative to our hand tank draft). Simulations of the beta, "
         "not measurements. Do not hand-edit.", "",
         "| Class | Spec (build) | Simulated as | Best on the training dummy | vs current | Best in a raid | vs current |", "|---|---|---|---|---|---|---|"]
    for cls, specs in res["classes"].items():
        for spec, r in specs.items():
            if not r:
                continue
            cur = r["current"]
            cells = []
            for setting in (["raid"] if r["tank"] else ["dummy", "raid"]):
                vals = {race: v[setting] for race, v in r["races"].items() if setting in v}
                best = max(vals, key=vals.get)
                base = vals.get(cur)
                cells += [f"{LABEL.get(best, best)} ({vals[best]:.3f})" if r["tank"] else f"{LABEL.get(best, best)} ({vals[best]:.0f})",
                          f"{(vals[best] / base - 1) * 100:+.1f}%" if base else "-"]
            if r["tank"]:
                cells = ["-", "-"] + cells
            o.append(f"| {cls} | {spec} (`{r['build']}`) | {LABEL.get(cur, cur)} | " + " | ".join(cells) + " |")
    o += ["", "Full tables: `_reference/data/race-sweep.json`. Weapon racials (Orc axes, Human swords, Dwarf maces) count only with the "
          "matching weapon in the spec's gear preset.", ""]
    OUT_MD.write_text("\n".join(o) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("classes", nargs="*")
    ap.add_argument("--iterations", type=int, default=20000)
    a = ap.parse_args()
    repo = run.repo_path(argparse.Namespace(repo=None))
    res = json.load(open(OUT_JSON, encoding="utf-8")) if OUT_JSON.exists() else {"classes": {}}
    for cls, specs in run.SPECS.items():
        if cls.startswith("_") or (a.classes and cls not in a.classes):
            continue
        for spec, entry in specs.items():
            if not isinstance(entry, dict) or "apl" not in entry:
                continue
            r = sweep(cls, spec, a, repo)
            res["classes"].setdefault(cls, {})[spec] = r
            print(f"{cls} {spec}: " + (", ".join(f"{k} {v}" for k, v in (r or {}).get("races", {}).items()) if r else "no report"), flush=True)
            res["date"] = datetime.date.today().isoformat()
            OUT_JSON.write_text(json.dumps(res, indent=1) + "\n", encoding="utf-8")
    render(res)
    print(f"wrote {OUT_MD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
