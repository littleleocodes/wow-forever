"""Talents that grant an ability the build's rotation never casts (2026-10-02, user report: "the new Frost mage spec takes Arcane Blast
but then never uses the ability in its rotation ... just a wasted talent point. I'm sure there are other examples as well").

    python _reference/data/raidsim/unused_abilities.py [classes] [--write]

For every raid build of ours raced in an entry (specs.json `builds`, the entry's last race report), every talent that grants an active
ability (spell_probe.talent_abilities: the talent's name is an active spell of the class spellbook) is checked against the build's own
casts in the race and the rotation's pre-pull actions (forms and buffs cast before the pull). A talent with no cast is then measured
by removal in the simulator (the build's setting: the training dummy, a full raid for `-parse` builds; 12,000 fights, one seed, common
random numbers) and classified:
- `automatic`: removing it costs DPS although nothing casts it: the simulator applies it from the talent or the class options
  (Trueshot Aura as a party buff, Demonic Sacrifice of the configured demon). A player must cast it: the raid page says so.
- `prerequisite`: another talent the build takes requires it (the point is the price of that talent).
- `situational`: a defensive ability (an absorb, a dodge cooldown, a heal, damage taken reduced) a player casts when needed.
- `wasted`: none of these: filler_audit.py moves such points (since 2026-10-02) in our hand and derived builds; the scorer's `opt-*`
  exports are regenerated by its own optimizer.
--write: `raidsim/unused-abilities.json` (render_modes.py reads it for the raid pages) and `_reference/unused-abilities.md` (generated).
"""
import argparse
import datetime
import importlib.util
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path[:0] = [str(ROOT / "_reference/data"), str(HERE)]
import paths  # noqa: E402
import spec_modes as SM  # noqa: E402


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


SP = _load("spell_probe", HERE / "spell_probe.py")
A = SP.A
R = A.R
OUT = HERE / "unused-abilities.json"
PAGE = ROOT / "_reference" / "unused-abilities.md"
TODAY = datetime.date.today().isoformat()
ZERO = 0.002   # removal under 0.2%: the talent does nothing for this build here
DEFENSIVE = re.compile(r"absorb|dodge|damage taken|reduces? (?:all )?(?:physical )?damage|heal", re.I)


def spell_book(cls):
    """{spell name: (every rank's id, the top rank's tooltip)} from the beta spellbook."""
    out = {}
    for tab in json.load(open(ROOT / "_reference/data/forever-spells" / f"{cls}.json", encoding="utf-8")).get("tabs", []):
        for sp in tab.get("spells", []):
            ranks = [r for r in sp.get("ranks", []) if r.get("id")]
            ids, text = out.get(sp.get("name", ""), (set(), ""))
            out[sp.get("name", "")] = (ids | {int(r["id"]) for r in ranks}, (str(ranks[-1].get("text", "")) if ranks else "") or text)
    return out


def apl_ids(path, key):
    try:
        apl = json.load(open(path, encoding="utf-8"))
    except (OSError, ValueError):
        return set()
    acc, todo = set(), [apl.get(key, [])]
    while todo:
        x = todo.pop()
        if isinstance(x, dict):
            for k, v in x.items():
                if k == "spellId" and isinstance(v, int):
                    acc.add(v)
                else:
                    todo.append(v)
        elif isinstance(x, list):
            todo += x
    return acc


def requires(cls):
    """{talent: {talents it requires}} from the beta tree data (`prereq` ids are tree/talent slugs)."""
    data = json.load(open(ROOT / "_reference/data/forever-talents" / f"{cls}.json", encoding="utf-8"))
    slug = {t["id"] if "/" in str(t.get("id", "")) else "": t["name"] for tr in data["trees"] for t in tr["talents"]}
    tail = {str(t.get("id", "")).split("/")[-1]: t["name"] for tr in data["trees"] for t in tr["talents"]}
    out = {}
    for tr in data["trees"]:
        for t in tr["talents"]:
            pre = t.get("prereq")
            if pre:
                pid = str(pre.get("id", ""))
                out.setdefault(t["name"], set()).add(slug.get(pid) or tail.get(pid.split("/")[-1], pid))
    return out


SACRIFICE = {"Imp": "+15% Shadow damage", "Succubus": "+15% Fire damage", "Voidwalker": "2% of your mana every 4 sec", "Felhunter": "3% of your health every 4 sec"}


def advice(cls, entry, talent, kind, needed_by):
    """What the raid page tells the player about a talent the rotation does not cast."""
    if kind == "automatic":
        opts = ((entry.get("spec") or {}).get(cls) or {}).get("options", {}).get("classOptions", {})
        if talent == "Demonic Sacrifice" and opts.get("sacrificeSummon"):
            d = opts.get("summon", "Imp")
            return f"before the pull, summon your {d} and sacrifice it ({SACRIFICE.get(d, 'its buff')} for 2 hours; summoning any demon cancels it)"
        if talent == "Demonic Sacrifice" and opts.get("pactSacrifice"):
            d, out = opts["pactSacrifice"], opts.get("summon", "demon")
            return (f"before the pull, summon your {d} and sacrifice it ({SACRIFICE.get(d, 'its buff')}), then summon your {out}: "
                    f"Demonic Pact keeps the {d}'s buff while another demon is out")
        if talent == "Soul Link":
            return "turn it on with your demon out (it lasts while the demon lives)"
        if talent == "Trueshot Aura":
            return "turn it on before the pull"
        return "cast it before the pull and keep it up (the simulator applies it for you, so the rotation has no line for it)"
    if kind == "prerequisite":
        return f"taken because {', '.join(needed_by)} requires it"
    if kind == "situational":
        return "a defensive or healing spell: cast it when you need it, it is not part of the damage rotation"
    return "not cast by the rotation"


def casts_of(row, ids):
    return sum(a.get("casts") or 0 for a in (row or {}).get("actions") or [] if a.get("spellId") in ids)


def audit(classes, its=12000):
    R.set_game("forever")
    repo = R.repo_path(argparse.Namespace(repo=None))
    rows = []
    for cls in classes:
        abil = {t for t, _, _, _ in SP.talent_abilities(cls)}
        book = spell_book(cls)
        req = requires(cls)
        trees = R.load_trees(repo, cls)
        builds = {b["id"]: b for b in json.load(open(paths.builds_json("forever", cls), encoding="utf-8"))["builds"]}
        for entry_name, e in R.SPECS.get(cls, {}).items():
            if not isinstance(e, dict) or "apl" not in e:
                continue
            rep_path = paths.raidsim_dir(cls) / f"{entry_name}.json"
            if not rep_path.exists():
                continue
            rep = {x["label"]: x for x in json.load(open(rep_path, encoding="utf-8"))["results"]}
            pre = apl_ids(R.apl_path(e, repo, R.setting(e)), "prepullActions") | apl_ids(R.apl_path(e, repo, "raid"), "prepullActions")
            cand = {}   # build id -> (flat, [talents with no cast in the race and no pre-pull line])
            for bid in e.get("builds", []):
                b, row = builds.get(bid), rep.get(bid)
                if not b or not row or row.get("error"):
                    continue
                flat = {n: r for items in b["allocation"].values() for n, r in items}
                ts = [t for t in sorted(set(flat) & abil) if not (row.get("casts") or {}).get(t) and not (book.get(t, (set(), ""))[0] & pre)]
                if ts:
                    cand[bid] = (flat, ts)
            if not cand:
                continue
            own = {bid: ("raid" if bid.endswith("-parse") or e.get("tank") else R.setting(e)) for bid in cand}
            res = {}
            for setting in ("dummy", "raid"):   # the builds in both settings (a raid-only line is a use); removal runs in the build's own
                blist = [{"label": f"b|{bid}", "talents": R.talents_string(trees, flat)} for bid, (flat, _) in cand.items()]
                blist += [{"label": f"r|{bid}|{t}", "talents": R.talents_string(trees, {k: v for k, v in flat.items() if k != t})}
                          for bid, (flat, ts) in cand.items() if own[bid] == setting for t in ts]
                res[setting] = A.bench(e, repo, blist, its, 1, setting, f"unused-{cls}")
            for bid, (flat, ts) in cand.items():
                for t in ts:
                    ids = book.get(t, (set(), ""))[0]
                    if casts_of(res["dummy"].get(f"b|{bid}"), ids) + casts_of(res["raid"].get(f"b|{bid}"), ids) > 0:
                        continue   # cast in one of the settings
                    base, rem = res[own[bid]].get(f"b|{bid}") or {}, res[own[bid]].get(f"r|{bid}|{t}") or {}
                    loss = 1 - (A.value(rem, base, bool(e.get("tank"))) or 1.0)
                    needed_by = sorted(n for n in flat if t in req.get(n, set()))
                    if loss >= ZERO:
                        kind = "automatic"
                    elif needed_by:
                        kind = "prerequisite"
                    elif DEFENSIVE.search(book.get(t, (set(), ""))[1]):
                        kind = "situational"
                    else:
                        kind = "wasted"
                    rows.append({"class": cls, "entry": entry_name, "build": bid, "spec": SM.spec_of(cls, builds[bid]), "talent": t,
                                 "ranks": flat[t], "setting": own[bid], "removal_loss": round(loss, 4), "kind": kind, "needed_by": needed_by,
                                 "advice": advice(cls, e, t, kind, needed_by)})
    return rows


def write(rows):
    OUT.write_text(json.dumps({"date": TODAY, "rows": rows}, indent=1) + "\n", encoding="utf-8")
    order = {"wasted": 0, "automatic": 1, "prerequisite": 2, "situational": 3}
    o = ["# Talents whose ability the rotation never casts (generated)", "",
         f"> Generated by `_reference/data/raidsim/unused_abilities.py` on {TODAY} from the last race of every raid entry and a removal run of "
         "each talent (12,000 fights). Do not hand-edit.", "",
         "A talent that grants an ability is only worth its point when the build uses it. *Automatic*: the simulator applies it without a "
         "rotation line (removing it costs DPS), so a player must cast it before the pull. *Prerequisite*: the price of the talent named. "
         "*Situational*: a defensive spell cast when needed. *Wasted*: none of these; `filler_audit.py` moves such points in our hand and "
         "derived builds (the scorer's `opt-*` builds are its optimizer's own).", "",
         "| Class | Entry | Build | Talent | Kind | Removal costs | What the player does |", "|---|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: (order[r["kind"]], r["class"], r["entry"], r["build"])):
        o.append(f"| {r['class']} | {r['entry']} | {r['build']} | {r['talent']} {r['ranks']} | {r['kind']} | {r['removal_loss']:+.1%} | {r['advice']} |")
    o += ["", "*" + ", ".join(f"{sum(r['kind'] == k for r in rows)} {k}" for k in order) + ".*"]
    PAGE.write_text("\n".join(o) + "\n", encoding="utf-8")
    print(f"wrote {PAGE.relative_to(ROOT).as_posix()} and {OUT.relative_to(ROOT).as_posix()}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("classes", nargs="*")
    ap.add_argument("--iterations", type=int, default=12000)
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    rows = audit(a.classes or SM.CLASSES, a.iterations)
    for r in rows:
        print(f"{r['class']:8s} {r['entry']:20s} {r['build']:34s} {r['talent']} {r['ranks']} [{r['setting']}] {r['kind']:12s} {r['removal_loss']:+.2%}  {r['advice']}")
    print(", ".join(f"{sum(r['kind'] == k for r in rows)} {k}" for k in ("wasted", "automatic", "prerequisite", "situational")))
    if a.write:
        write(rows)


if __name__ == "__main__":
    main()
