"""Talent values on the training dummy vs in a full raid, for every damage spec's best builds (2026-10-01, user request after the
Arms miss: "analyze the spec that beat us ... find why and then use that analysis to optimize the remaining specs").

    python _reference/data/raidsim/setting_audit.py [classes] [--iterations 20000] [--write]

Why: our raid builds are searched on the training dummy (own buffs only). The community's 37/14/0 Arms build beat ours by 13.9% in a
full raid while tying on the dummy, and one talent explained it: Mortal Strike is 2.1% of an Arms warrior's damage on the dummy (it
costs 30 rage, and a dummy-buffed warrior is short of rage) but 10.7% in a full raid (raid attack power, crit and armor debuffs raise
both its hits and the rage that pays for it): removing it cost 0.8% on the dummy, 13.2% in the raid, so the dummy search let it go.
Our build also held 7 points (Booming Voice, Deflection) worth 0% in both settings. The stat weights barely move between the settings
(Arms in attack-power terms: hit 4.3 -> 5.5, crit 1.5 -> 1.9), so gear is not the issue; talent values measured on a starved dummy are.

For every damage entry this measures, for its best dummy build and its best full-raid build (by the last race and the environments
report), every talent's removal effect in both settings with common random numbers, and lists
  * talents whose value differs by more than --flag between the settings (resource-limited abilities and their talents, buffs the
    raid supplies anyway), and
  * talents worth less than --zero in both settings (free points: they belong in utility, per filler_audit.py).
Writes `_reference/setting-audit.md` and `raidsim/setting-audit.json` (generated).
"""
import argparse
import datetime
import importlib.util
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path[:0] = [str(ROOT / "_reference/data"), str(HERE)]
import paths  # noqa: E402

_s = importlib.util.spec_from_file_location("aplopt", HERE / "apl_opt.py")
A = importlib.util.module_from_spec(_s)
_s.loader.exec_module(A)
R = A.R
OUT_JSON = HERE / "setting-audit.json"
OUT_MD = ROOT / "_reference/setting-audit.md"


def best_builds(cls, spec):
    """(best build by dummy DPS, best build by full-raid DPS) of ours in this entry, from the environments report (or the race)."""
    data = {b["id"]: b for b in json.load(open(paths.builds_json("forever", cls), encoding="utf-8"))["builds"]}
    f = paths.raidsim_dir(cls) / f"{spec}-environments.json"
    rows = json.load(open(f, encoding="utf-8"))["results"] if f.exists() else []
    vals = {}
    for r in rows:
        if r["label"] in data and isinstance(r.get("dps"), dict):
            d = r["dps"]
            vals[r["label"]] = ((d.get("dummy") or {}).get("dps") if isinstance(d.get("dummy"), dict) else d.get("dummy"),
                                (d.get("raid") or {}).get("dps") if isinstance(d.get("raid"), dict) else d.get("raid"))
    vals = {k: v for k, v in vals.items() if v[0] and v[1]}
    if not vals:
        return None, None, data
    return max(vals, key=lambda k: vals[k][0]), max(vals, key=lambda k: vals[k][1]), data


def audit(cls, spec, its):
    e = R.SPECS[cls][spec]
    repo = R.repo_path(argparse.Namespace(repo=None))
    tr = R.load_trees(repo, cls)
    bd, br, data = best_builds(cls, spec)
    if not bd:
        return None
    out = {"entry": spec, "dummy_build": bd, "raid_build": br, "builds": {}}
    for bid in dict.fromkeys([bd, br]):
        al = R.alloc_of(data[bid])
        bl = [{"label": "base", "talents": R.talents_string(tr, al)}] + [
            {"label": n, "talents": R.talents_string(tr, {k: v for k, v in al.items() if k != n})} for n in sorted(al)]
        res = {}
        for where in ("dummy", "raid"):
            rows = A.bench(e, repo, bl, its, 1, where, f"setaudit-{cls}")
            base = rows["base"]["dps"]
            res[where] = {"dps": base, "talents": {n: 1 - rows[n]["dps"] / base for n in al if rows.get(n) and rows[n].get("dps")}}
        out["builds"][bid] = {"ranks": al, **res}
    return out


def render(rec, a):
    o = ["# Talent values: training dummy vs full raid", "",
         f"> Generated by `_reference/data/raidsim/setting_audit.py` on {datetime.date.today().isoformat()} (ElliotWood/Forever simulator, "
         f"{a.iterations} iterations, common random numbers, the equal-tier gear). Value = DPS lost when the talent is removed. Do not hand-edit.", "",
         "Why this exists: the community's 37/14/0 Arms build beat ours by 13.9% in a full raid and tied on the dummy. Mortal Strike was "
         "the whole gap (0.8% of DPS on the dummy, 13.2% in a full raid): a rage-starved dummy warrior rarely affords it. Builds searched "
         "on the dummy drop such talents. **Flagged** = the value differs by more than "
         f"{a.flag:.0%} between the settings; **free** = under {a.zero:.1%} in both.", ""]
    for cls, specs in sorted(rec.items()):
        for spec, r in sorted(specs.items()):
            if not r:
                continue
            o += [f"## {cls.capitalize()} — {spec}", ""]
            for bid, b in r["builds"].items():
                role = " and ".join(x for x, k in (("dummy", r["dummy_build"]), ("full raid", r["raid_build"])) if k == bid)
                o += [f"**{bid}** (best on the {role}): {b['dummy']['dps']:.0f} DPS on the dummy, {b['raid']['dps']:.0f} in a full raid.", ""]
                rows = []
                for n, rk in sorted(b["ranks"].items()):
                    d, rr = b["dummy"]["talents"].get(n, 0), b["raid"]["talents"].get(n, 0)
                    tag = "**flagged**" if abs(rr - d) > a.flag else ("free" if abs(d) < a.zero and abs(rr) < a.zero else "")
                    if tag:
                        rows.append(f"| {n} | {rk} | {d:+.1%} | {rr:+.1%} | {tag} |")
                o += (["| Talent | Ranks | Dummy | Full raid | |", "|---|---|---|---|---|"] + rows + [""]) if rows else ["Nothing flagged.", ""]
    return "\n".join(o) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("classes", nargs="*")
    ap.add_argument("--iterations", type=int, default=20000)
    ap.add_argument("--flag", type=float, default=0.02)
    ap.add_argument("--zero", type=float, default=0.002)
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    R.set_game("forever")
    rec = json.load(open(OUT_JSON, encoding="utf-8")) if OUT_JSON.exists() else {}
    for cls, es in R.SPECS.items():
        if cls.startswith("_") or (a.classes and cls not in a.classes):
            continue
        for spec, e in es.items():
            if not isinstance(e, dict) or e.get("tank") or not e.get("gear"):
                continue
            r = audit(cls, spec, a.iterations)
            rec.setdefault(cls, {})[spec] = r
            if r:
                flagged = [(bid, n) for bid, b in r["builds"].items() for n in b["ranks"]
                           if abs(b["raid"]["talents"].get(n, 0) - b["dummy"]["talents"].get(n, 0)) > a.flag]
                print(f"== {cls} {spec}: dummy {r['dummy_build']}, raid {r['raid_build']}; flagged {flagged}", flush=True)
            if a.write:
                OUT_JSON.write_text(json.dumps(rec, indent=1) + "\n", encoding="utf-8")
    if a.write:
        OUT_MD.write_text(render(rec, a), encoding="utf-8")
        print(f"wrote {OUT_MD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
