"""Write the "Raid sim" section of every class README and `_reference/raidsim-summary.md` from the raid-sim reports.

    python _reference/data/render_raidsim_sections.py [classes...]

Reads `<class>/research/raid/raidsim/<spec>.json` (written by `_reference/data/raidsim/run.py --write`). Generated text; the
section sits before the "Fight lab" section of each class README. `rebuild.py --steps regen` runs it.
"""
import datetime
import json
import pathlib
import re
import sys
import paths  # noqa: E402
import readme_sections as rs  # noqa: E402
import sim_info as SI  # noqa: E402  (which simulator a record ran on)

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
CLASSES = ["mage", "priest", "warlock", "hunter", "warrior", "rogue", "paladin", "shaman", "druid"]
HEAD = "## Raid sim (community simulator, level 60)"
SECTION = re.compile(r"^## Raid sim \(community simulator, level 60\)\n.*?(?=^## |\Z)", re.S | re.M)
SUMMARY = ROOT / "_reference/raidsim-summary.md"


def load(cls, game="forever"):
    d = paths.raidsim_dir(cls, game)
    if not d.exists():
        return []
    out = []
    for p in sorted(d.glob("*.json")):
        if p.name.endswith("-calibration.json") or p.name.endswith("-environments.json"):
            continue
        r = json.load(open(p, encoding="utf-8"))
        if "results" in r:
            out.append(r)
    return out


def load_env(cls, game="forever"):
    d = paths.raidsim_dir(cls, game)
    out = []
    for p in sorted(d.glob("*-environments.json")) if d.exists() else []:
        r = json.load(open(p, encoding="utf-8"))
        if r.get("results"):
            out.append(r)
    return out


def mana_rows(cls, reports):
    """One row per spec model whose raid calibration measured a mana deficit (`<spec>-calibration.json` "mana")."""
    out = []
    for r in reports:
        cal = paths.raidsim_dir(cls) / f"{r['spec']}-calibration.json"
        if not cal.exists():
            continue
        c = json.load(open(cal, encoding="utf-8"))
        m = c.get("mana") or {}
        builds = m.get("builds") or {}
        if not builds:
            continue
        d = [v["deficit"] for v in builds.values()]
        lim = m.get("limit")
        pure = sorted({k.split(" -", 1)[1] for k in (m.get("removals") or {})})
        sims = {t["talent"]: t["sim"] for t in c.get("talents", [])}
        talents = ", ".join(f"{t} {sims[t] * 100:.1f}%" for t in sorted(pure, key=lambda t: -sims.get(t, 0)) if t in sims and sims[t] >= 0.001) or "-"
        out.append(f"| `{r['spec']}` | {min(d) * 100:.1f}-{max(d) * 100:.1f}% | "
                   + (f"{lim['loss']:.2f} / {lim['cap']:.2f} | {lim['rms'] * 100:.1f} | {talents} |" if lim else "no limit (under 1% for every build) | - | - |"))
    return out


def render(cls, reports, classic=()):
    o = [HEAD, "",
         f"[`raidsim/`](raidsim/) runs every raid build through the community's raid simulator (these reports: "
         f"{SI.summary([dict(r['sim'], date=r.get('date')) for r in reports])}) with the entry's gear set and rotation, {reports[0]['sim']['iterations']} iterations per build, next to "
         "the simulator's preset talent builds. **DPS specs are ranked on a boss-level training dummy with only your own buffs** (the class's self-buffs and the spec's "
         "standard consumables; no raid or party buffs, no debuffs from others): the races, calibrations and the adopt step run there, while the pages rank raid builds by DPS in a full raid (2026-10-02). Tanks are measured in the raid setting "
         "(full buffs, boss melee). Same gear and rotation for every build, so only the talents differ. OOM s = seconds per fight out of mana: on the dummy a spec "
         "that lives on Blessing of Wisdom and Mana Spring in a raid runs dry, and its mana talents weigh more there than in a raid. The ranking of our "
         "builds against the simulator's own is the DPS ranking section above; this section shows the scorer's view and the other settings. Section generated by "
         f"`_reference/data/render_raidsim_sections.py` on {datetime.date.today().isoformat()} — do not hand-edit.", "",
         "| Spec model | Setting | Build | Split | DPS | vs best | OOM s | Scorer |", "|---|---|---|---|---|---|---|---|"]
    for r in reports:
        rows = sorted(r["results"], key=lambda x: -(x["dps"] or 0))
        if not rows:   # an entry without builds or presets (the Shockadin survey target)
            continue
        best = rows[0]["dps"] or 1.0
        for x in rows:
            setting = "dummy" if r["sim"].get("setting") == "dummy" else "raid"
            if x.get("error"):
                o.append(f"| `{r['spec']}` | {setting} | `{x['label']}` | {x['split'] or '-'} | error | - | - | - |")
                continue
            name = f"`{x['label']}`" if x["ours"] else x["label"]
            sc = f"{x['scorer'] * 100:+.0f}%" if x.get("scorer") is not None else "-"
            oom = f"{x['oom_seconds']:.0f}" if x.get("oom_seconds") is not None else "-"
            o.append(f"| `{r['spec']}` | {setting} | {name} | {x['split'] or '-'} | {x['dps']:.0f} | {(x['dps'] - best) / best * 100:+.1f}% | {oom} | {sc} |")
    o += ["", "Scorer = the stats model's own score of the allocation for its raid profile (relative to a talentless character; comparable within a spec model only). "
          "Tanks: DPS with the tank flag set (threat and mitigation are in the report JSON). Healers are not simulated (the simulator has no healing rotations for them).", ""]
    mana = mana_rows(cls, reports)
    if mana:
        o += ["**Mana on the training dummy**: what each build loses to mana there (the damage the same build gains with every mana-only buff on: "
              "Mana Spring, Mana Tide, Blessing of Wisdom, Innervates, Judgement of Wisdom). Out-of-mana seconds miss most of it (a Frost mage's Evocation, "
              "a warlock's Life Taps, the rotation's mana conditions). The scorer's mana limit (spec model `mana_limit`, fitted by `raidsim/calibrate.py`) "
              "cuts the mana-bound damage by min(cap, max(0, loss - (sustain - 1))); fit error = RMS over the builds and the removal runs of the pure mana "
              "talents, in points of deficit. Simulator numbers, not measurements.", "",
              "| Spec model | Builds lose to mana | Mana limit: loss / cap | Fit error | Mana talents: DPS lost when removed (simulator) |", "|---|---|---|---|---|"] + mana + [""]
    envs = [r for r in load_env(cls)]
    if envs:
        o += ["**DPS by environment** ([reports](raidsim/)): the same builds on the boss-level training dummy with your own buffs (the ranking above), on an "
              "in-game style level-60 dummy (never dies, own buffs), in a full raid (phase-1 gear, every raid buff and debuff minus the one this spec brings, "
              "raid consumables) and at the theoretical maximum (best gear preset, everything on, 180 s and 60 s). A build that wins on the dummy but not in "
              "the raid column wins on its own buffs only. `opt-<spec>-parse` is the parse build: personal DPS only, the raid brings every buff. "
              "Simulator numbers, not measurements.", "",
              "| Spec model | Build | Split | Dummy | Dummy 60 | Raid | Maximum | Max 60 s |", "|---|---|---|---|---|---|---|---|"]
        for r in envs:
            for x in sorted(r["results"], key=lambda x: -(x["dps"].get("dummy") or x["dps"].get("raid") or 0)):
                name = f"`{x['label']}`" if x["ours"] else x["label"]
                cell = lambda k: (f"{x['dps'][k]:.0f}" if x["dps"].get(k) else "-")   # noqa: E731
                o.append(f"| `{r['spec']}` | {name} | {x['split'] or '-'} | {cell('dummy')} | {cell('dummy60')} | {cell('raid')} | {cell('max')} | {cell('max60')} |")
        o.append("")
    if classic:
        o += [f"**Classic Era check** — [`../talents/classic-baseline/raidsim/`](../talents/classic-baseline/raidsim/): the same run of our Classic-era community builds through the upstream "
              f"wowsims/classic simulator (commit {classic[0]['sim']['commit']}, its phase-1 presets), which the scorer's classic-era models are calibrated against. "
              "Our builds there are the community's; a preset ahead of them means the simulator's rotation prefers other talents.", "",
              "| Spec model | Build | Split | DPS | vs best | Scorer |", "|---|---|---|---|---|---|"]
        for r in classic:
            rows = sorted(r["results"], key=lambda x: -(x["dps"] or 0))
            best = rows[0]["dps"] or 1.0
            for x in rows:
                if x.get("error"):
                    o.append(f"| `{r['spec']}` | `{x['label']}` | {x['split'] or '-'} | error | - | - |")
                    continue
                name = f"`{x['label']}`" if x["ours"] else x["label"]
                sc = f"{x['scorer'] * 100:+.0f}%" if x.get("scorer") is not None else "-"
                o.append(f"| `{r['spec']}` | {name} | {x['split'] or '-'} | {x['dps']:.0f} | {(x['dps'] - best) / best * 100:+.1f}% | {sc} |")
        o.append("")
    return "\n".join(o) + "\n"


def main():
    classes = sys.argv[1:] or CLASSES
    summary = ["# Raid sim — every class at a glance", "",
               f"> Generated by `_reference/data/render_raidsim_sections.py` on {datetime.date.today().isoformat()} from `<class>/research/raid/raidsim/*.json` "
               f"({{SIMS}} runs of our raid builds and the simulator's presets: same gear, rotation and buffs per spec, so talents alone differ). "
               "Simulations of the community's model of the beta, not measurements. Do not hand-edit.", "",
               "| Class | Spec model | Best of our builds | DPS | Best sim preset | DPS | Our optimizer build | DPS |", "|---|---|---|---|---|---|---|---|"]
    classic_rows = []
    env_rows = []
    all_sims = []   # every report's simulator block: the header names them (sim_info.summary)
    for cls in sorted(CLASSES):   # the summary covers every class, the sections only the classes asked for (2026-10-09: a one-class run cut it)
        reports = load(cls)
        if not reports:
            continue
        all_sims += [dict(r["sim"], date=r.get("date")) for r in reports]
        classic = load(cls, "classic-era")
        text = render(cls, reports, classic) if cls in classes else None
        for r in load_env(cls) + load_env(cls, "classic-era"):
            game = "Forever" if r.get("game", "forever") == "forever" else "Classic"
            ours = [x for x in r["results"] if x["ours"] and x["dps"].get("max")]
            theirs = [x for x in r["results"] if not x["ours"] and x["dps"].get("max")]
            parse = next((x for x in ours if x["label"].endswith("-parse")), None)
            bo = max(ours, key=lambda x: x["dps"]["max"]) if ours else None
            bt = max(theirs, key=lambda x: x["dps"]["max"]) if theirs else None
            if bo:
                cell = lambda k: (f"{bo['dps'][k]:.0f}" if bo["dps"].get(k) else "-")   # noqa: E731
                env_rows.append(f"| {cls} | {game} | `{r['spec']}` | `{bo['label']}` ({bo['split']}) | {cell('dummy')} | {cell('dummy60')} | {cell('raid')} | {bo['dps']['max']:.0f} | {cell('max60')} | "
                                + (f"`{parse['label']}` {parse['dps']['max']:.0f}" if parse else "-") + " | " + (f"{bt['label'].replace('sim preset: ', '')} {bt['dps']['max']:.0f}" if bt else "-") + " |")
        for r in classic:
            ours = [x for x in r["results"] if x["ours"] and x.get("dps")]
            theirs = [x for x in r["results"] if not x["ours"] and x.get("dps")]
            bo = max(ours, key=lambda x: x["dps"]) if ours else None
            bt = max(theirs, key=lambda x: x["dps"]) if theirs else None
            main = next((x for x in r["results"] if x.get("source_shares")), None)
            split = ", ".join(f"{k} {v * 100:.0f}%" for k, v in sorted(main["source_shares"].items(), key=lambda kv: -kv[1]) if v >= 0.005) if main else "-"
            unm = f" (unmatched {main['unmatched_share'] * 100:.0f}%)" if main and main["unmatched_share"] >= 0.05 else ""
            bo_d = f"{bo['dps']:.0f}" if bo else "-"
            bt_d = f"{bt['dps']:.0f}" if bt else "-"
            classic_rows.append(f"| {cls} | `{r['spec']}` | {('`' + bo['label'] + '`') if bo else '-'} | {bo_d} | "
                                f"{bt['label'].replace('sim preset: ', '') if bt else '-'} | {bt_d} | {split}{unm} |")
        if text is not None:
            rs.splice_ordered(paths.scenario_readme(cls, "raid"), "raid", "## Raid sim", text)
            rs.drop(ROOT / cls / "README.md", "## Raid sim")   # moved to raid/README.md (2026-09-27 layout)
        for r in reports:
            ours = [x for x in r["results"] if x["ours"] and x.get("dps")]
            theirs = [x for x in r["results"] if not x["ours"] and x.get("dps")]
            opt = [x for x in ours if x["label"].startswith("opt-")]
            bo = max(ours, key=lambda x: x["dps"]) if ours else None
            bt = max(theirs, key=lambda x: x["dps"]) if theirs else None
            bp = max(opt, key=lambda x: x["dps"]) if opt else None
            summary.append(f"| {cls} | `{r['spec']}` | {('`' + bo['label'] + '`') if bo else '-'} | {bo['dps']:.0f} | {bt['label'].replace('sim preset: ', '') if bt else '-'} | "
                           f"{bt['dps']:.0f} | {('`' + bp['label'] + '`') if bp else '-'} | {bp['dps']:.0f} |" if bo and bt and bp else
                           f"| {cls} | `{r['spec']}` | {('`' + bo['label'] + '`') if bo else '-'} | {round(bo['dps']) if bo else '-'} | - | - | - | - |")
        if text is not None:
            print(f"{cls}: raid sim section written ({len(reports)} specs)")
    summary.append("")
    if env_rows:
        summary += ["## DPS by environment: dummy, raid, maximum", "",
                    "The best of our builds per spec model on the boss-level training dummy with your own buffs (Forever: the setting the raid DPS calibrations and "
                    "races use), on a level-60 dummy (Forever: own buffs; Classic: no buffs), in a full raid (phase-1 gear, full buffs minus the one the spec brings) "
                    "and at the theoretical maximum (best gear preset, every buff and debuff on, consumables, 180 s and 60 s); "
                    "the parse build (`opt-<spec>-parse`: personal DPS only) and the best simulator preset at the maximum for comparison. Reports: `<class>/research/raid/raidsim/<spec>-environments.md` (Forever), `<class>/research/talents/classic-baseline/raidsim/` (Classic).", "",
                    "| Class | Game | Spec model | Best build | Dummy | Dummy 60 | Raid | Maximum | Max 60 s | Parse build (max) | Best preset (max) |", "|---|---|---|---|---|---|---|---|---|---|---|"]
        summary += env_rows
        summary.append("")
    if classic_rows:
        summary += ["## Classic Era check (upstream wowsims/classic)", "",
                    "Our Classic-era community builds (`<class>/research/talents/classic-baseline/builds.json`) through the upstream wowsims/classic simulator with its phase-1 presets: "
                    "the damage split the scorer's classic-era models now use, and how the community builds fare against the simulator's own preset talents. "
                    "Reports: `<class>/research/talents/classic-baseline/raidsim/<spec>.md`.", "",
                    "| Class | Spec model | Best of our builds | DPS | Best sim preset | DPS | Damage split (model sources) |", "|---|---|---|---|---|---|---|"]
        summary += classic_rows
        summary.append("")
    summary[2] = summary[2].replace("{SIMS}", SI.summary(all_sims) or "the raid simulator's")
    SUMMARY.write_text("\n".join(summary) + "\n", encoding="utf-8")
    print(f"wrote {SUMMARY.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
