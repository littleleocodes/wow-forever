"""Cross-class fight-lab summary: `_reference/fightlab-summary.md` (generated) from every class's fight-lab report.

    python _reference/data/fightlab/summary.py --write

Reads `<class>/research/leveling/fightlab/<spec>.json` (the spec named in each module's PIPELINE), `mob_stats.json` and
`last-rebuild.json` (race winners, rounds), and writes one page: time per kill, deaths and downtime by class and level,
the optimizer build vs the hand draft, gear tiers, each class's top talents, what is not simulated and the mob table.
"""
import argparse
import datetime
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "_reference/data/scorer"))
sys.path.insert(0, str(HERE))   # last: `run` must be the fight lab runner
sys.path.append(str(pathlib.Path(__file__).resolve().parents[1]))   # _reference/data: paths.py
import paths  # noqa: E402
from data_build import BUILD as DATA_BUILD  # noqa: E402
from run import MODULES  # noqa: E402

OUT = ROOT / "_reference/fightlab-summary.md"
LEVELS = ["15", "20", "30", "40", "50", "60"]


def pipeline(cls):
    return dict(__import__(MODULES[cls][0]).PIPELINE)


def load(cls):
    P = pipeline(cls)
    path = paths.fightlab_dir(cls) / f"{P['spec']}.json"
    if not path.exists():
        return P, None
    return P, json.load(open(path, encoding="utf-8"))


def pct(x):
    return f"{x * 100:+.0f}%"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    reports = {cls: load(cls) for cls in MODULES}
    mob = json.load(open(HERE / "mob_stats.json", encoding="utf-8")) if (HERE / "mob_stats.json").exists() else None
    last = json.load(open(HERE / "last-rebuild.json", encoding="utf-8")) if (HERE / "last-rebuild.json").exists() else {}
    fights = {r["fights"] for _, r in reports.values() if r}
    o = ["# Fight lab — every class at a glance", "",
         f"> Generated by `_reference/data/fightlab/summary.py` on {datetime.date.today().isoformat()} from the per-class fight-lab reports "
         f"(`<class>/research/leveling/fightlab/<spec>.md`, {'/'.join(str(f) for f in sorted(fights))} fights per configuration). Same-level normal mobs, gear from the Classic 1.12 item database (greens), "
         f"beta client {DATA_BUILD} ability numbers; mob health, damage, armor and the caster share come from the Classic 1.12 creature database "
         "(unverified for Forever). Every number is a simulation of assumptions listed in `_reference/data/fightlab/tables.py`, not a beta measurement. Do not hand-edit.", ""]
    # ---- time per kill
    o += ["## Time per kill (seconds, fight + downtime + deaths) — the optimizer's leveling build", "",
          "| Class | Spec model | Build | " + " | ".join(f"L{L}" for L in LEVELS) + " | Kills/hour at 60 |", "|---|---|---|" + "---|" * (len(LEVELS) + 1)]
    for cls, (P, r) in reports.items():
        if not r:
            o.append(f"| {cls} | {P['spec']} | - | " + " | ".join("-" for _ in LEVELS) + " | - |")
            continue
        cells = [f"{r['levels'][L]['time_per_kill']:.1f}" if L in r["levels"] else "-" for L in LEVELS]
        k60 = f"{r['levels']['60']['kills_per_hour']:.0f}" if "60" in r["levels"] else "-"
        o.append(f"| {cls} | `{r['spec']}` | `{r['build']}` | " + " | ".join(cells) + f" | {k60} |")
    o.append("")
    # ---- hand draft vs optimizer
    o += ["## Hand draft vs. the optimizer's build (time per kill, hand draft relative to the optimizer)", "",
          "| Class | Hand draft | " + " | ".join(f"L{L}" for L in LEVELS) + " | Race winner (sim) |", "|---|---|" + "---|" * (len(LEVELS) + 1)]
    for cls, (P, r) in reports.items():
        if not r:
            continue
        hand = r["compare"].get(P["hand"], {})
        cells = []
        for L in LEVELS:
            if L in hand and L in r["levels"]:
                d = (hand[L]["time_per_kill"] - r["levels"][L]["time_per_kill"]) / r["levels"][L]["time_per_kill"]
                cells.append(f"{hand[L]['time_per_kill']:.1f} ({pct(d)})")
            else:
                cells.append("-")
        race = last.get("classes", {}).get(cls, {}).get("race", {})
        winner = race.get("winner", "-") if race else "-"
        o.append(f"| {cls} | `{P['hand']}` | " + " | ".join(cells) + f" | {winner} |")
    o += ["", "Positive = the hand draft is slower. The race winner is the fastest build over all levels among the hand draft and every saved candidate "
          "(`rebuild.py`, `last-rebuild.json`); the class README says which build is recommended and why.", ""]
    # ---- deaths, downtime, casters
    o += ["## Deaths, downtime and caster pulls", "",
          "| Class | Deaths/100 kills L30 | L60 | Downtime/kill L30 | L60 | Fight L30 | L60 | Caster pulls L30 | Interrupts/kill L60 |", "|---|---|---|---|---|---|---|---|---|"]
    for cls, (P, r) in reports.items():
        if not r:
            continue
        g = lambda L, k, f="{:.1f}": (f.format(r["levels"][L][k]) if L in r["levels"] and k in r["levels"][L] else "-")
        o.append(f"| {cls} | {g('30', 'deaths_per_100')} | {g('60', 'deaths_per_100')} | {g('30', 'downtime_per_kill')}s | {g('60', 'downtime_per_kill')}s | "
                 f"{g('30', 'fight_mean')}s | {g('60', 'fight_mean')}s | {g('30', 'caster_share', '{:.0%}')} | {g('60', 'interrupts_per_kill', '{:.2f}')} |")
    o.append("")
    # ---- gear tiers
    if any(r and r.get("gear_tiers") for _, r in reports.values()):
        o += ["## Gear tiers (time per kill, optimizer build): greens vs. dungeon blues (Classic 1.12 item database)", "",
              "| Class | L30 greens | L30 blues | L60 greens | L60 blues |", "|---|---|---|---|---|"]
        for cls, (P, r) in reports.items():
            if not r or not r.get("gear_tiers"):
                continue
            blues = r["gear_tiers"].get("blues", {})
            cells = []
            for L in ("30", "60"):
                base = r["levels"].get(L)
                b = blues.get(L)
                cells.append(f"{base['time_per_kill']:.1f}s" if base else "-")
                cells.append(f"{b['time_per_kill']:.1f}s ({pct((b['time_per_kill'] - base['time_per_kill']) / base['time_per_kill'])})" if b and base else "-")
            o.append(f"| {cls} | " + " | ".join(cells) + " |")
        o.append("")
    # ---- top talents
    o += ["## Top talents (time per kill lost when the talent is removed from the optimizer build)", "",
          "| Class | Level 30 | Level 60 | Measures ~0 at 60 |", "|---|---|---|---|"]
    for cls, (P, r) in reports.items():
        if not r or not r.get("deltas"):
            continue
        cells = []
        for L in ("30", "60"):
            rows = sorted(r["deltas"].get(L, {}).get("rows", []), key=lambda x: -x["sim_delta"])[:3]
            cells.append(", ".join(f"{x['talent']} {pct(x['sim_delta'])}" for x in rows) or "-")
        zero = [x["talent"] for x in r["deltas"].get("60", {}).get("rows", []) if abs(x["sim_delta"]) < 0.005]
        o.append(f"| {cls} | {cells[0]} | {cells[1]} | {', '.join(zero) or '-'} |")
    o.append("")
    # ---- rebuild log
    if last.get("last_run"):
        lr = last["last_run"]
        o += ["## Last rebuild", "",
              f"`rebuild.py` ran on {lr['date'][:10]} for {', '.join(lr['classes'])} (steps {', '.join(lr['steps'])}; {lr['seconds'] // 60} min). Per class:", ""]
        for cls, rr in last.get("classes", {}).items():
            rounds = rr.get("rounds", [])
            conv = "converged" if rr.get("converged") else ("no calibration" if not rounds else "did not converge")
            race = rr.get("race", {})
            means = ", ".join(f"{(rr['hand'] if b == 'main' else pathlib.Path(b).stem)} {m:.1f}s" for b, m in sorted(race.get("mean", {}).items(), key=lambda kv: kv[1]))
            o.append(f"- **{cls}**: {len(rounds)} calibration round(s), {conv}; race {means or 'not run'}" + (f"; FAILED {rr['failed']}" if rr.get("failed") else ""))
        o.append("")
    # ---- not simulated
    o += ["## Not simulated (per class)", ""]
    for cls, (P, r) in reports.items():
        if not r:
            continue
        cm = __import__(MODULES[cls][0])
        o.append(f"- **{cls}**: {cm.NOT_MODELLED}")
    o.append("")
    # ---- mob table
    if mob:
        o += ["## Mob assumptions by level (Classic 1.12 creature database, normal outdoor mobs weighted by spawn count)", "",
              "| Level | Health (median) | Melee swing | Armor | Casters | Templates / spawns |", "|---|---|---|---|---|---|"]
        for L, an in mob["anchors"].items():
            if int(L) < 10:
                continue
            o.append(f"| {L} | {an['health']} (±{an['health_spread'] * 100:.0f}%) | {an['dmg']} per {an['swing']}s | {an['armor']} | {an['caster_share'] * 100:.0f}% | {an['templates']} / {an['spawns']} |")
        o += ["", f"Source: {mob['source']}. A caster stands at range and casts a bolt for 1.6x its melee swing every 3.5 s until interrupted "
              "(Counterspell, Kick, Earth Shock, Silence, Feral Charge, stuns), then runs in. WoW: Forever may have retuned creatures; `sensitivity.md` per class "
              "moves mob health, damage and the caster share to show which conclusions survive.", ""]
    text = "\n".join(o) + "\n"
    if a.write:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
    else:
        print(text)


if __name__ == "__main__":
    main()
