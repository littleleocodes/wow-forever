"""Sensitivity of the fight-lab conclusions to the assumptions the beta cannot yet confirm.

    python _reference/data/fightlab/sensitivity.py mage --spec frost-leveling --builds opt-frost-leveling-leveling-st leveling-frost \
        --levels 30,60 --fights 1500 --write

For each variation of an unverified table constant (root-break chance, mob health, mob damage), re-runs the builds and
reports time per kill and the build ranking, plus the value of the loop-defining talents (Ice Lance, Shatter) when
removed, so the reader can see which conclusions survive. Writes <class>/research/leveling/fightlab/sensitivity.md.
"""
import argparse
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))
sys.path.append(str(pathlib.Path(__file__).resolve().parents[1]))   # _reference/data: paths.py
import paths  # noqa: E402

import tables  # noqa: E402
from run import allocation_at, apply_overrides, load_build, simulate  # noqa: E402

VARIATIONS = [
    ("baseline", []),
    ("root breaks on 10% of hits", ["ROOT_BREAK_CHANCE=0.10"]),
    ("root breaks on 40% of hits", ["ROOT_BREAK_CHANCE=0.40"]),
    ("mobs have 20% less health", ["MOB_HP_MULT=0.8"]),
    ("mobs have 20% more health", ["MOB_HP_MULT=1.2"]),
    ("mobs hit 30% harder", ["MOB_DMG_MULT=1.3"]),
    ("pushback 1.0 s per hit", ["PUSHBACK_FIRST=1.0", "PUSHBACK_NEXT=1.0"]),
    ("weapons 20% better (blues)", ["WEAPON_DPS_MULT=1.2"]),
    ("dungeon blues (item database)", ["GEAR_TIER=blues"]),
    ("gear stats 20% better", ["GEAR_STAT_MULT=1.2"]),
    ("no caster mobs", ["MOB_CASTER_SHARE=0"]),
    ("30% caster mobs", ["MOB_CASTER_SHARE=0.3"]),
    ("20% of mobs run at 20% health", ["RUNNER_SHARE=0.2"]),
    # 2026-10-18 (audit rows 70-71): the old assumptions the lab dropped, and the client's creature health curve
    ("2.5% partial resists (the assumption before 2026-10-18)", ["PARTIAL_RESIST_LOSS=0.025"]),
    ("channel pushback 0.5 s per hit (before 2026-10-18)", ["CHANNEL_PUSHBACK=0"]),
    ("mob health by the client's ExpectedStat (1.35x at 20, 1.13x at 60)", ["MOB_HP_SHAPE=expected"]),
    ("every rank at its level-60 amount (no rank level scaling, before 2026-10-18)", ["RANK_LEVEL_SCALING=0"]),
]
DEFAULTS = {k: getattr(tables, k) for k in ("ROOT_BREAK_CHANCE", "MOB_HP_MULT", "MOB_DMG_MULT", "PUSHBACK_FIRST", "PUSHBACK_NEXT", "WEAPON_DPS_MULT", "GEAR_STAT_MULT", "GEAR_TIER", "MOB_CASTER_SHARE", "RUNNER_SHARE",
                                         "PARTIAL_RESIST_LOSS", "CHANNEL_PUSHBACK", "MOB_HP_SHAPE", "RANK_LEVEL_SCALING")}


def reset():
    for k, v in DEFAULTS.items():
        setattr(tables, k, v)
        import engine
        if hasattr(engine, k):
            setattr(engine, k, v)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cls")
    ap.add_argument("--spec", default="frost-leveling")
    ap.add_argument("--builds", nargs="+", required=True)
    ap.add_argument("--levels", default="30,60")
    ap.add_argument("--fights", type=int, default=1500)
    ap.add_argument("--talents", nargs="*", default=None, help="talents to remove per row (default: the class module's KEY_TALENTS)")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--set", action="append", default=[], help="tables.py overrides applied under every row (MOBS_PER_PULL=4 for the AoE profile)")
    a = ap.parse_args()
    if a.talents is None:
        from run import class_module
        a.talents = class_module(a.cls).KEY_TALENTS
    levels = [int(x) for x in a.levels.split(",")]
    builds = {bid: load_build(a.cls, bid) for bid in a.builds}
    rows = []
    for label, sets in VARIATIONS:
        reset()
        apply_overrides(a.set)
        apply_overrides(sets)
        for L in levels:
            res = {}
            for bid, b in builds.items():
                alloc = allocation_at(b, L)
                base = simulate(a.cls, alloc, L, a.spec, a.fights, 1, 0)
                res[bid] = {"tpk": base["time_per_kill"], "deaths": base["deaths_per_100"], "removed": {}}
                for t in a.talents:
                    if t in alloc:
                        r = simulate(a.cls, {k: v for k, v in alloc.items() if k != t}, L, a.spec, a.fights, 1, 0)
                        res[bid]["removed"][t] = (r["time_per_kill"] - base["time_per_kill"]) / base["time_per_kill"]
            rows.append((label, L, res))
            print(label, L, {bid: round(r["tpk"], 1) for bid, r in res.items()}, {bid: {t: round(v * 100, 1) for t, v in r["removed"].items()} for bid, r in res.items()})
    reset()
    if a.write:
        out = paths.fightlab_dir(a.cls) / "sensitivity.md"
        o = [f"# Fight lab sensitivity — {a.cls} {a.spec}", "",
             f"> Generated by `_reference/data/fightlab/sensitivity.py` ({a.fights} fights per configuration). Each row changes one assumption the beta has not confirmed "
             "(`tables.py`) and shows time per kill per build and the value of the loop-defining talents when removed. A conclusion that holds across rows does not depend on the assumption.", ""]
        head = "| Assumption | Level | " + " | ".join(f"{bid} time/kill" for bid in a.builds) + " | Best build | " + " | ".join(f"{a.builds[0]}: −{t}" for t in a.talents) + " |"
        o.append(head)
        o.append("|---|---|" + "---|" * (len(a.builds) + 1 + len(a.talents)))
        for label, L, res in rows:
            best = min(res, key=lambda b: res[b]["tpk"])
            cells = [f"{res[b]['tpk']:.1f}s (deaths {res[b]['deaths']:.1f}/100)" for b in a.builds]
            tal = [f"{res[a.builds[0]]['removed'].get(t, 0) * 100:+.0f}%" if t in res[a.builds[0]]["removed"] else "-" for t in a.talents]
            o.append(f"| {label} | {L} | " + " | ".join(cells) + f" | {best} | " + " | ".join(tal) + " |")
        o.append("")
        out.write_text("\n".join(o) + "\n", encoding="utf-8")
        print(f"wrote {out}")


if __name__ == "__main__":
    main()
