"""Write `<class>/research/leveling/guide.md` for every class (and the "Guide, rotation and respec plan" section of leveling/README.md): the leveling guide the fight lab and the scorer imply (generated).

    python _reference/data/render_leveling_guides.py [classes...]

Sources: the class module's PIPELINE (spec model, hand draft, extra specs), `<class>/research/leveling/fightlab/<spec>.json`
(kill times, deaths, downtime, talent values, gear tiers, caster share), the hand draft's `order` in `proposed-builds.json`,
`<class>/research/leveling/respec-plan.md` (the recommended schedule line) and the module's DESCRIPTION / NOT_MODELLED.
Every number is a simulation of stated assumptions (Classic 1.12 creature and item data, beta-client abilities), not a
measurement. `rebuild.py --steps regen` runs this after the fight-lab sections.
"""
import datetime
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "_reference/data/scorer"))
sys.path.insert(0, str(HERE / "fightlab"))
from run import MODULES  # noqa: E402
import paths  # noqa: E402
import readme_sections as rs  # noqa: E402

BRACKETS = [("20", "levels 15-25"), ("30", "levels 25-35"), ("40", "levels 35-45"), ("50", "levels 45-55"), ("60", "level 55-60")]


def pct(x):
    return f"{x * 100:+.0f}%"


def feel(r):
    """One sentence on how a bracket plays, from the level's numbers."""
    parts = []
    if r["deaths_per_100"] >= 3:
        parts.append(f"{r['deaths_per_100']:.0f} deaths per 100 kills: play carefully")
    elif r["deaths_per_100"] >= 1:
        parts.append(f"about {r['deaths_per_100']:.0f} death per 100 kills")
    else:
        parts.append("deaths are rare")
    share = r["downtime_per_kill"] / max(0.1, r["time_per_kill"])
    if share >= 0.35:
        parts.append(f"{share:.0%} of the time is downtime (drinking, eating, healing): mana and health economy rule")
    elif share >= 0.15:
        parts.append(f"{share:.0%} downtime")
    else:
        parts.append("almost no downtime")
    if r.get("caster_share", 0) >= 0.15:
        parts.append(f"{r['caster_share']:.0%} of pulls are casters")
    return "; ".join(parts) + "."


def render(cls, P, r, build, respec_line, cm):
    spec, hand, opt = P["spec"], P["hand"], P["opt"]
    levels = sorted(r["levels"], key=int)
    top = levels[-1]
    o = [f"# {cls.title()} — leveling guide (generated)", "",
         f"> Generated by `_reference/data/render_leveling_guides.py` on {datetime.date.today().isoformat()} from the fight lab report "
         f"[`{spec}`](fightlab/{spec}.md), the build [`{hand}`](builds/{hand}.md) and the "
         "[respec plan](respec-plan.md). Beta-client 1.60.1.70009 abilities, Classic 1.12 creature and item data, "
         "same-level mobs one at a time: simulations of stated assumptions, not measurements. Do not hand-edit.", "",
         "## The build and its order", "",
         f"`{hand}` — {build.get('summary', '').split(' Previous summary:')[0][:600]}", ""]
    if build.get("order"):
        o += ["| Levels | Tree | Talent | Points |", "|---|---|---|---|"]
        for st in build["order"]:
            o.append(f"| {st['levels']} | {st['tree']} | {st['talent']} | {st['points']} |")
        o.append("")
    if respec_line:
        o += [f"Respec plan: {respec_line}", ""]
    o += ["## What each bracket feels like", "",
          "| Level | Bracket | Fight | Time per kill | Kills/hour | Deaths/100 | Downtime/kill | In dungeon blues |", "|---|---|---|---|---|---|---|---|"]
    blues = (r.get("gear_tiers") or {}).get("blues", {})
    for L in levels:
        x = r["levels"][L]
        b = blues.get(L)
        label = dict(BRACKETS).get(L, f"level {L}")
        o.append(f"| {L} | {label} | {x['fight_mean']:.0f}s | {x['time_per_kill']:.0f}s | {x['kills_per_hour']:.0f} | {x['deaths_per_100']:.1f} | {x['downtime_per_kill']:.0f}s | "
                 + (f"{b['time_per_kill']:.0f}s ({pct((b['time_per_kill'] - x['time_per_kill']) / x['time_per_kill'])}) |" if b else "- |"))
    o.append("")
    for L in levels:
        o.append(f"- **Level {L}:** {feel(r['levels'][L])}")
    o.append("")
    o += ["## How the fights go", "", cm.DESCRIPTION, ""]
    deltas = r.get("deltas") or {}
    if deltas:
        o += ["## Talents that carry the build", ""]
        for L in sorted(deltas, key=int):
            rows = sorted(deltas[L]["rows"], key=lambda x: -x["sim_delta"])[:6]
            o.append(f"- **Level {L}:** " + ", ".join(f"{x['talent']} ({pct(x['sim_delta'])} time per kill without it)" for x in rows) + ".")
        zero = sorted({x["talent"] for L in deltas for x in deltas[L]["rows"] if abs(x["sim_delta"]) < 0.005})
        if zero:
            o.append(f"- **Free to move** (no measurable effect single-target): " + ", ".join(zero) + ".")
        o.append("")
    extras = []
    for er in P.get("extra_reports", []):
        ep = paths.fightlab_dir(cls) / f"{er['spec']}.json"
        if ep.exists():
            e = json.load(open(ep, encoding="utf-8"))
            comp = next(iter(e["compare"].values()), {}) if e.get("compare") else {}
            cells = []
            for L in ("30", "60"):
                if L in e["levels"] and L in comp:
                    cells.append(f"L{L} {pct((e['levels'][L]['time_per_kill'] - comp[L]['time_per_kill']) / comp[L]['time_per_kill'])}")
            extras.append(f"`{er['spec']}` ({e['build']}): " + ", ".join(cells) + " vs the main build")
    if extras:
        o += ["## Other specs while leveling", "", "Time per kill relative to the main spec's optimizer build on the same mobs (positive = slower): " + "; ".join(extras) + ".", ""]
    o += ["## Not simulated", "", cm.NOT_MODELLED, ""]
    return "\n".join(o) + "\n"


def main():
    classes = sys.argv[1:] or list(MODULES)
    for cls in classes:
        cm = __import__(MODULES[cls][0])
        P = dict(cm.PIPELINE)
        rp = paths.fightlab_dir(cls) / f"{P['spec']}.json"
        if not rp.exists():
            print(f"{cls}: no report")
            continue
        r = json.load(open(rp, encoding="utf-8"))
        data = json.load(open(ROOT / cls / "research/talents/forever/proposed-builds.json", encoding="utf-8"))
        build = next((b for b in data["builds"] if b["id"] == P["hand"]), {})
        respec_line = ""
        rpath = paths.respec_plan(cls)
        if rpath.exists():
            m = re.search(r"^Total: (.*)$", rpath.read_text(encoding="utf-8"), re.M)
            respec_line = m.group(1) if m else ""
        guide = paths.leveling_guide(cls)
        guide.parent.mkdir(parents=True, exist_ok=True)
        guide.write_text(render(cls, P, r, build, respec_line, cm), encoding="utf-8")
        readme = paths.scenario_readme(cls, "leveling")
        page = paths.build_page_by_id("forever", cls, P["hand"])
        sec = ["## Guide, rotation and respec plan", "",
               f"- [Leveling guide](guide.md): the recommended build `{P['hand']}` level by level, what each bracket feels like and what the fight lab does not model.",
               "- [Rotation](rotation.md): the priority the fight lab plays and what each leveling build casts per kill, level by level.",
               "- [Respec plan](respec-plan.md): when a respec while leveling pays for itself" + (f" ({respec_line})" if respec_line else "") + "."]
        if page:
            sec.append(f"- Recommended build: [{P['hand']}]({paths.rel(readme, page)}).")
        rs.splice_ordered(readme, "leveling", "## Guide, rotation and respec plan", "\n".join(sec))
        print(f"{cls}: leveling/guide.md written")


if __name__ == "__main__":
    main()
