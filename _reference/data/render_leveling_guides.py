BRACKETS = [("20", "levels 15-25"), ("30", "levels 25-35"), ("40", "levels 35-45"), ("50", "levels 45-55"), ("60", "level 55-60")]


def pct(x):
    return f"{x * 100:+.0f}%"


def feel(r):
    """One sentence on how a bracket plays, from the level's numbers."""
    parts = []
    if r["deaths_per_100"] >= 3:
        parts.append(f"{r['deaths_per_100']:.0f} deaths per 100 kills: play carefully")
    elif r["deaths_per_100"] >= 1:
        parts.append(f"about {r['deaths_per_100']:.0f} death per 100 kills")
    else:
        parts.append("deaths are rare")
    share = r["downtime_per_kill"] / max(0.1, r["time_per_kill"])
    if share >= 0.35:
        parts.append(f"{share:.0%} of the time is downtime (drinking, eating, healing): mana and health economy rule")
    elif share >= 0.15:
        parts.append(f"{share:.0%} downtime")
    else:
        parts.append("almost no downtime")
    if r.get("caster_share", 0) >= 0.15:
        parts.append(f"{r['caster_share']:.0%} of pulls are casters")
    return "; ".join(parts) + "."


def report_of(cls, bid, rot):
    """(report path, report, per-level rows) of a fight-lab report that played build `bid` with rotation `rot`, else (None, None, None)."""
    fr = rrot.fl_runner()
    for p, r in rrot.fl_reports(cls):
        if p.stem.endswith("-aoe"):
            continue
        if r["build"] == bid and r["spec"] == rot:
            return p, r, r["levels"]
        per = (r.get("compare") or {}).get(bid)
        if per and fr.spec_of_build(cls, bid, r["spec"]) == rot:
            return p, r, per
    return None, None, None


def open_values(cls, bid):
    """The open leveling search's talent values at level 60 for a build it wrote: {talent: {"ranks", "seconds", "per_point"}} or {}."""
    f = HERE / "fightlab" / "open" / f"{cls}.json"
    if not f.exists():
        return {}
    try:
        st = json.load(open(f, encoding="utf-8"))
    except ValueError:
        return {}
    for rec in (st.get("rotations") or {}).values():
        if bid in ((rec.get("builds") or {}).get("written") or []):
            return rec.get("values") or {}
    return {}


def render(cls, P, pick, picks, respec_line, cm):
    b = pick["build"]
    bid, rot = b["id"], pick["rotation"]
    page = paths.leveling_guide(cls)
    rp, r, per = report_of(cls, bid, rot)
    o = [f"# {cls.title()} — leveling guide (generated)", "",
         f"> Generated by `_reference/data/render_leveling_guides.py` on {datetime.date.today().isoformat()} for the build the "
         f"[leveling pages](../../leveling/README.md) recommend: {pick['name']}'s {rrot.label_md(cls, bid, page)}, playing the fight lab's "
         f"`{rot}` rotation ([rotation page](rotation.md#{rot}))"
         + (f", report [`{rp.stem}`](fightlab/{rp.stem}.md)" if rp else "") + ". Beta-client " + DATA_BUILD + " abilities, Classic 1.12 "
         "creature and item data, same-level mobs one at a time: simulations of stated assumptions, not measurements. Do not hand-edit.", "",
         "## The build and its order", "",
         f"**{pick['name']}** ([player page](../../leveling/{pick['slug']}.md)) — `{bid}`: "
         f"{b.get('summary', '').split(' Previous summary:')[0][:600]}", ""]
    if b.get("order"):
        o += ["| Levels | Tree | Talent | Points |", "|---|---|---|---|"]
        for st in b["order"]:
            o.append(f"| {st['levels']} | {st['tree']} | {st['talent']} | {st['points']} |")
        o.append("")
    else:
        o += ["This build has no talent order recorded: the fight lab played it with every point from level 10.", ""]
    levels = sorted(pick["levels"])
    o += ["## Every spec's page build", "",
          "Level-weighted time per kill (seconds, higher levels count more) of the build each spec's leveling page shows first; "
          "✅ = recommended (the fastest, or within 3% of it).", "",
          "| Spec | Page build | Rotation | " + " | ".join(f"L{L}" for L in levels) + " | Weighted |", "|---|---|---|" + "---|" * (len(levels) + 1)]
    for x in picks:
        o.append(f"| [{x['name']}](../../leveling/{x['slug']}.md){' ✅' if x['recommended'] else ''} | {rrot.label_md(cls, x['build']['id'], page)} | "
                 f"{x['rotation'] or '-'} | " + " | ".join(f"{x['levels'][L]:.1f}" if L in x["levels"] else "-" for L in levels)
                 + (f" | {x['weighted']:.1f} |" if x["weighted"] else " | - |"))
    o.append("")
    if respec_line:
        o += [f"The stats model's respec plan (its own optimizer builds, not the page build): {respec_line} ([respec plan](respec-plan.md)).", ""]
    o += ["## What each bracket feels like", ""]
    if per:
        blues = ((r.get("gear_tiers") or {}).get("blues", {})) if r["build"] == bid else {}
        o += ["| Level | Bracket | Fight | Time per kill | Kills/hour | Deaths/100 | Downtime/kill | In dungeon blues |", "|---|---|---|---|---|---|---|---|"]
        lv = sorted(per, key=int)
        for L in lv:
            x = per[L]
            bl = blues.get(L)
            label = dict(BRACKETS).get(L, f"level {L}")
            o.append(f"| {L} | {label} | {x['fight_mean']:.0f}s | {x['time_per_kill']:.0f}s | {x['kills_per_hour']:.0f} | {x['deaths_per_100']:.1f} | {x['downtime_per_kill']:.0f}s | "
                     + (f"{bl['time_per_kill']:.0f}s ({pct((bl['time_per_kill'] - x['time_per_kill']) / x['time_per_kill'])}) |" if bl else "- |"))
        o.append("")
        for L in lv:
            o.append(f"- **Level {L}:** {feel(per[L])}")
        o.append("")
        if any(abs(pick["levels"][int(L)] - per[L]["time_per_kill"]) > 0.01 * per[L]["time_per_kill"] for L in lv if int(L) in pick["levels"]):
            o += [f"The page's times per kill come from another race of the same build and rotation (other seeds or fights), so they differ "
                  f"from this report's by up to {max(abs(pick['levels'][int(L)] / per[L]['time_per_kill'] - 1) for L in lv if int(L) in pick['levels']):.0%}.", ""]
    else:
        o += ["| Level | Bracket | Time per kill | Kills/hour |", "|---|---|---|---|"]
        for L in levels:
            t = pick["levels"][L]
            o.append(f"| {L} | {dict(BRACKETS).get(str(L), f'level {L}')} | {t:.0f}s | {3600 / t:.0f} |")
        o += ["", "Fight time, deaths and downtime are not recorded for this build: its times come from the race of the search that found "
              "it, which keeps times only.", ""]
    o += ["## How the fights go", ""]
    st = rrot.leveling_steps().get(cls, {}).get(rot)
    if rot == P["spec"] or (rp and rot == r["spec"]):
        o += [rrot.fl_description(cls, rot), ""]
    if st:
        o += ["The rotation in the player page's words:", ""] + (["Before the fight: " + " ".join(st["before"]), ""] if st.get("before") else [])
        o += [f"{i}. {t}" for i, t in enumerate(st.get("steps") or [], 1)] + [""]
        if st.get("between"):
            o += ["Between fights: " + " ".join(st["between"]), ""]
    tuned = rrot.fl_tuning_text(cls, rot)
    if tuned:
        o += [tuned, ""]
    deltas = (r.get("deltas") or {}) if (r and r["build"] == bid) else {}
    vals = open_values(cls, bid)
    if deltas:
        o += ["## Talents that carry the build", ""]
        for L in sorted(deltas, key=int):
            rows = sorted(deltas[L]["rows"], key=lambda x: -x["sim_delta"])[:6]
            o.append(f"- **Level {L}:** " + ", ".join(f"{x['talent']} ({pct(x['sim_delta'])} time per kill without it)" for x in rows) + ".")
        zero = sorted({x["talent"] for L in deltas for x in deltas[L]["rows"] if abs(x["sim_delta"]) < 0.005})
        if zero:
            o.append("- **Free to move** (no measurable effect single-target): " + ", ".join(zero) + ".")
        o.append("")
    elif vals:
        top = sorted(vals.items(), key=lambda kv: -kv[1]["seconds"])
        o += ["## Talents that carry the build", "",
              "- **Level 60** (seconds per kill lost without the talent, the open leveling search): "
              + ", ".join(f"{t} (+{v['seconds']:.1f} s)" for t, v in top[:6] if v["seconds"] > 0) + "."]
        zero = sorted(t for t, v in vals.items() if abs(v["seconds"]) < 0.1)
        if zero:
            o.append("- **About zero at 60** (under 0.1 s per kill): " + ", ".join(zero) + ".")
        o.append("")
    o += ["## Not simulated", "", cm.NOT_MODELLED, ""]
    return "\n".join(o) + "\n"


def respec_total(cls):
    """The respec plan's recommended schedule total, e.g. "**35.7 h** (60.3% faster than talentless), no respec" (no end stop)."""
    rpath = paths.respec_plan(cls)
    if not rpath.exists():
        return ""
    m = re.search(r"^Total: (.*)$", rpath.read_text(encoding="utf-8"), re.M)
    return m.group(1).rstrip(".") if m else ""   # 2026-10-15 page audit B17: the line ends in a stop, quoted inside parentheses


def main():
    classes = sys.argv[1:] or list(MODULES)
    for cls in classes:
        cm = __import__(MODULES[cls][0])
        P = dict(cm.PIPELINE)
        picks = rrot.page_picks(cls, "leveling")
        picks_timed = [x for x in picks if x["weighted"]]
        if not picks_timed:
            print(f"{cls}: no leveling page build with times")
            continue
        pick = picks_timed[0]
        respec_line = respec_total(cls)
        guide = paths.leveling_guide(cls)
        guide.parent.mkdir(parents=True, exist_ok=True)
        guide.write_text(render(cls, P, pick, picks, respec_line, cm), encoding="utf-8")
        readme = paths.scenario_readme(cls, "leveling")
        page = paths.build_page_by_id("forever", cls, pick["build"]["id"])
        sec = ["## Guide, rotation and respec plan", "",
               f"- [Leveling guide](guide.md): the recommended build ({pick['name']}, `{pick['build']['id']}`) level by level, what each "
               "bracket feels like and what the fight lab does not model.",
               "- [Rotation](rotation.md): the build each leveling page picks, the rotation it plays and what each leveling build casts per kill, level by level.",
               "- [Respec plan](respec-plan.md): when a respec while leveling pays for itself, by the stats model" + (f" ({respec_line})" if respec_line else "") + "."]
        if page:
            sec.append(f"- Recommended build: [{pick['build']['id']}]({paths.rel(readme, page)}) ({pick['name']}; player page: "
                       f"[{pick['name']} leveling](../../leveling/{pick['slug']}.md)).")
        rs.splice_ordered(readme, "leveling", "## Guide, rotation and respec plan", "\n".join(sec))
        print(f"{cls}: leveling/guide.md written ({pick['build']['id']})")


if __name__ == "__main__":
    main()
