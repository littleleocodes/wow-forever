"""Write `<class>/research/leveling/guide.md` for every class (and the "Guide, rotation and respec plan" section of leveling/README.md): the leveling guide the fight lab and the scorer imply (generated).

    python _reference/data/render_leveling_guides.py [classes...]

The guide is about the build the player leveling pages recommend (2026-10-15 page audit B5: it had described the fight-lab pipeline's
hand draft, which the pages no longer pick in most classes): the fastest spec's page build as render_modes.py picks it
(render_rotations.page_picks), its talent order, its time per kill by level, the rotation it plays (the player page's steps from
leveling-steps.json and the tuned rules) and, where a fight-lab report played that build with that rotation, its fight time, deaths,
downtime and talent values; the open leveling search's talent values for an open-search build. Every spec's page build is listed with its
time per kill. Sources: the class module's PIPELINE and report `<class>/research/leveling/fightlab/<spec>.json`, the builds in
`proposed-builds.json`, the open-search records `fightlab/open/<class>.json`, `<class>/research/leveling/respec-plan.md` (the stats
model's schedule) and the module's DESCRIPTION / NOT_MODELLED. Every number is a simulation of stated assumptions (Classic 1.12 creature
and item data, beta-client abilities), not a measurement. `rebuild.py --steps regen` runs this after the fight-lab sections.
"""
